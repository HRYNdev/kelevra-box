package io.nekohasekai.sfa.bg

/**
 * Гистерезис на гашение туннеля дома.
 *
 * Полевые данные за неделю 31.10–07.11.2026: на одном телефоне автомат поднимал и гасил
 * ядро 204 раза (≈29 в сутки) — домашний вайфай дёргается, сеть меняется каждые
 * 20–30 с, и каждая смена принималась задвижкой без подтверждений (смена сети — довод).
 * Вне дома → поднять, дома → погасить, и так по кругу: каждый цикл — пересборка ядра и
 * разрыв соединений.
 *
 * Правило простое и несимметричное:
 *  - **уход из дома — сразу**, как и было: вне дома без туннеля трафик идёт открыто,
 *    задерживать подъём нельзя;
 *  - **приход домой — с выдержкой**: туннель гасим, только когда «дома» продержалось
 *    [holdMillis] подряд; любое наблюдение «не дома» или смена сети сбрасывает отсчёт.
 *
 * Дёрганье туда-сюда таким образом гасится само: пока вайфай моргает чаще выдержки,
 * туннель остаётся поднятым и через дом работает как через любую сеть; устоялся —
 * погасим. Цена — лишние секунды туннеля дома при настоящем возвращении.
 *
 * Класс не решает, что делать, — он только отвечает «можно ли уже гасить». Решение и
 * действие остаются за [AutoMode]. Без Android внутри — чтобы последовательность событий
 * из журнала можно было прогнать тестом.
 *
 * @param holdMillisOf сколько «дома» должно продержаться; читается на каждом вопросе
 *   (пульт `avtomat.dom_zaderzhka_millis`).
 */
internal class DomZaderzhka(private val holdMillisOf: () -> Long) {
    constructor(holdMillis: Long) : this({ holdMillis })

    /** С какого момента (elapsedRealtime) «дома» наблюдается непрерывно; 0 — не наблюдается. */
    var since: Long = 0L
        private set

    private val holdMillis: Long get() = holdMillisOf().coerceAtLeast(0L)

    /**
     * Очередное наблюдение захода.
     *
     * @param home заход увидел «дома».
     * @param networkChanged наблюдение сделано сразу после смены сети — отсчёт начинается заново:
     *   устойчивым состояние считается только без смен сети внутри выдержки.
     * @param now elapsedRealtime.
     */
    fun observe(home: Boolean, networkChanged: Boolean, now: Long) {
        since = when {
            !home -> 0L
            networkChanged || since == 0L -> now
            else -> since
        }
    }

    /** «Дома» продержалось достаточно — гасить можно. */
    fun ready(now: Long): Boolean = since != 0L && now - since >= holdMillis

    /** Отсчёт идёт, но выдержка ещё не набрана. */
    fun pending(now: Long): Boolean = since != 0L && !ready(now)

    /** Сколько ещё держать; 0 — уже можно или отсчёт не идёт. */
    fun leftMillis(now: Long): Long = if (since == 0L) 0L else (holdMillis - (now - since)).coerceAtLeast(0L)

    fun reset() {
        since = 0L
    }
}
