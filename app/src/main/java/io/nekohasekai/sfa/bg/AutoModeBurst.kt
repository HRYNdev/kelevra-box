package io.nekohasekai.sfa.bg

/**
 * Серия ускоренных перепроверок сразу после смены сети.
 *
 * Одного наблюдения на смене сети мало, и не потому, что оно неточное, а потому, что
 * оно **раннее**. Вайфай объявляется системе раньше, чем на нём заработает всё
 * остальное: адрес по DHCP, свои DNS-серверы, проверка интернета. Проба, сделанная
 * в эту секунду, честно отвечает про недоделанную сеть — и ответ уезжает в обычный
 * ритм, то есть на пять минут вперёд. Ровно так возвращение домой и стоило минуту.
 *
 * Поэтому после смены сети смотрим не один раз, а серией с растущими паузами
 * ([AutoMode.BURST_STEPS]: 1, 3, 8, 20 секунд) — и **обрываем её, как только обстановка
 * устоялась**: заход ничего не поменял и подтверждений никто не ждёт. Обычно это первый
 * же шаг серии, то есть цена одна лишняя проба.
 *
 * Разрешением метаться серия не является. Что она меняет — только скорость перепроверки;
 * решение по-прежнему принимает [AutoModeGate], и внутри серии он требует подтверждений
 * (на одно меньше обычного — обстановка доказанно только что поменялась, старый вердикт
 * заведомо просрочен).
 *
 * Без Android внутри — чтобы поведение можно было проверить, а не пересказать.
 */
internal class AutoModeBurst(private val steps: LongArray) {

    /** Индекс следующей паузы; -1 — серии сейчас нет. */
    private var step = -1

    val active: Boolean get() = step >= 0

    /** Сеть сменилась: серию начинаем заново, даже если предыдущая ещё шла. */
    fun restart() {
        step = 0
    }

    fun cancel() {
        step = -1
    }

    /**
     * @param settled заход ничего не поменял и подтверждений никто не ждёт.
     * @return пауза до следующей проверки, либо null — серия кончилась, дальше обычный ритм.
     */
    fun next(settled: Boolean): Long? {
        if (step < 0) return null
        // Шаг 0 — это заход, на котором сеть и сменилась: обстановка после него
        // «не менялась» по определению, обрывать серию на этом нельзя.
        if (settled && step > 0) {
            step = -1
            return null
        }
        if (step >= steps.size) {
            step = -1
            return null
        }
        return steps[step++]
    }
}
