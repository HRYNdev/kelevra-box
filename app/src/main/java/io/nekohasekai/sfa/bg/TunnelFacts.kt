package io.nekohasekai.sfa.bg

/**
 * Живо ли что-то от туннеля на самом деле — в противовес флагу «погашено».
 *
 * Флаг и действительность расходились. Ядро поднималось мимо автомата (перечитывание
 * конфига по расписанию, обновление подписки, экран настроек), флаг при этом оставался
 * «погашено», и гашение, глядя только на него, честно отвечало «уже погашено» и не
 * делало ничего: tun висел до ручного выключения сервиса. Одна сторона лечения —
 * не поднимать ядро дома ([BoxService.serviceReload0]); вторая здесь: решение гасить
 * принимается по факту, поэтому любой другой способ развести флаг с действительностью
 * лечится сам собой, а не ждёт своей заплатки.
 */
internal object TunnelFacts {
    /**
     * Есть ли что гасить прямо сейчас.
     *
     * @param suspendedFlag что записано в сервисе.
     * @param tunOpen tun открыт на самом деле — дескриптор жив.
     * @param roomLive ядро комнаты работает на самом деле.
     */
    fun suspendNeeded(suspendedFlag: Boolean, tunOpen: Boolean, roomLive: Boolean): Boolean =
        !suspendedFlag || tunOpen || roomLive

    /**
     * Можно ли пересобирать ядро (`startOrReloadService`) прямо сейчас.
     *
     * Нельзя, пока сервис останавливается или остановлен: командный сервер уже закрыт или
     * вот-вот закроется, и пересборка поднимет ядро-сироту, которое никто не закроет. Оно
     * держит общий вход 127.0.0.1:2412, и следующий старт падает «bind: address already
     * in use» (эмулятор 13.09.2026: стоп во время подъёма комнаты, комната встала через
     * 46 с после стопа и пересобрала ядро). Нельзя и при погашенном туннеле — дома ядра нет.
     */
    fun rebuildAllowed(serviceStopping: Boolean, suspendedFlag: Boolean): Boolean =
        !serviceStopping && !suspendedFlag

    /**
     * Выводить ли приложение из tun в ядре, которое собирается прямо сейчас.
     *
     * Ядру olcRTC нужен вывод всего пакета из tun ([BoxService.applyPerAppProxy]), и
     * решение ложится в список приложений мимо сети. Список держим постоянным на всё
     * время, пока комната нужна: при другом списке `establish` вообще не пробует обновить
     * сеть на месте («Handover not possible due to changes to allowed/denied apps»).
     *
     * Поэтому вывод держится не только пока комната поднята или поднимается, но и когда
     * туннель поднимают ради неё ([roomAhead]) и пока автомат её ищет ([roomSought]).
     *
     * @param vpn сервис работает как VPN — в режиме без tun выводить не из чего.
     * @param roomWanted комнату попросили и не отменили.
     * @param roomAhead туннель поднимают, чтобы следом поднять комнату.
     * @param roomReady ядро комнаты сейчас в комнате.
     * @param roomSought автомат стоит на комнате или ищет путь, либо комнату выбрал человек.
     */
    fun selfOutsideTun(
        vpn: Boolean,
        roomWanted: Boolean,
        roomAhead: Boolean,
        roomReady: Boolean,
        roomSought: Boolean,
    ): Boolean = vpn && (roomWanted || roomAhead || roomReady || roomSought)

    /**
     * Надо ли пересобрать ядро, чтобы его конфиг снова отвечал намерению.
     *
     * Работающее ядро помнит два решения: собрано ли оно под комнату (отказ QUIC, только
     * IPv4, остальное в комнату) и выведено ли приложение из tun. Разошлись с тем, что
     * нужно сейчас — пересобрать.
     *
     * Зачем это отдельным решением: пересборка закрывает прежний tun, и Android сносит
     * VPN-сеть, а новую заводит заново (замер на эмуляторе 16.09.2026: `networkDestroy`
     * идёт ПЕРЕД `networkCreate`, обновить сеть на месте уже нечем). Сделанная после
     * входа в комнату, такая пересборка попадает в собранную сессию: ядро комнаты видит
     * смену сети, LiveKit перезапускает ICE, и данные стоят десятки секунд. Значит
     * пересборка под комнату нужна ДО входа, а после входа её быть не должно.
     *
     * @param coreRoom работающее ядро собрано под комнату.
     * @param coreSelfOutside работающее ядро собрано с приложением вне tun.
     * @param wantRoom нужен ли конфиг под комнату сейчас.
     * @param wantSelfOutside нужен ли вывод приложения сейчас (см. [selfOutsideTun]).
     * @param roomBusy комнату поднимает сервис или присмотр — посреди входа не трогаем.
     */
    fun coreConfigStale(
        coreRoom: Boolean,
        coreSelfOutside: Boolean,
        wantRoom: Boolean,
        wantSelfOutside: Boolean,
        roomBusy: Boolean,
    ): Boolean = !roomBusy && (coreRoom != wantRoom || coreSelfOutside != wantSelfOutside)
}
