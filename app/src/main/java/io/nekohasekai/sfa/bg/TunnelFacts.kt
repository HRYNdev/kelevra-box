package io.nekohasekai.sfa.bg

/**
 * Живо ли что-то от туннеля на самом деле — в противовес флагу «погашено».
 *
 * Флаг и действительность расходились. Ядро поднималось мимо автомата (перечитывание
 * конфига по расписанию, обновление подписки, экран настроек), флаг при этом оставался
 * «погашено», и гашение, глядя только на него, честно отвечало «уже погашено» и не
 * делало ничего: tun висел до ручного выключения сервиса. Одна сторона лечения —
 * не поднимать ядро дома ([BoxService.serviceReload0]); вторая здесь: решение гасить
 * принимается по факту, поэтому любой другой способ развести флаг с действительностью
 * лечится сам собой, а не ждёт своей заплатки.
 */
internal object TunnelFacts {
    /**
     * Есть ли что гасить прямо сейчас.
     *
     * @param suspendedFlag что записано в сервисе.
     * @param tunOpen tun открыт на самом деле — дескриптор жив.
     * @param roomLive ядро комнаты работает на самом деле.
     */
    fun suspendNeeded(suspendedFlag: Boolean, tunOpen: Boolean, roomLive: Boolean): Boolean =
        !suspendedFlag || tunOpen || roomLive

    /**
     * Можно ли пересобирать ядро (`startOrReloadService`) прямо сейчас.
     *
     * Нельзя, пока сервис останавливается или остановлен: командный сервер уже закрыт или
     * вот-вот закроется, и пересборка поднимет ядро-сироту, которое никто не закроет. Оно
     * держит общий вход 127.0.0.1:2412, и следующий старт падает «bind: address already
     * in use» (эмулятор 13.09.2026: стоп во время подъёма комнаты, комната встала через
     * 46 с после стопа и пересобрала ядро). Нельзя и при погашенном туннеле — дома ядра нет.
     */
    fun rebuildAllowed(serviceStopping: Boolean, suspendedFlag: Boolean): Boolean =
        !serviceStopping && !suspendedFlag
}
