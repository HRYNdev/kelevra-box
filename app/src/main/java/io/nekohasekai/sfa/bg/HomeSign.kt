package io.nekohasekai.sfa.bg

/**
 * Признак дома: правила вокруг DNS-сводки, вынесенные из [AutoMode] отдельно и без
 * единого обращения к Android.
 *
 * Здесь три разных вопроса, и каждый стоил секунд или ложного переключения:
 *
 *  1. **Где дом возможен вообще** ([reachable]). Дом — это наш собственный роутер,
 *     а он раздаёт вайфай или кабель. В соте дома не бывает по устройству, и четыре
 *     запроса к резолверу там — чистая трата: замер 10.08.2026 показал до 2.5 секунд
 *     на каждом заходе и столько же перед самым стартом сервиса ([AutoMode.homeRightNow]),
 *     то есть человек ждал подключения ровно за тот вопрос, ответ на который известен
 *     заранее.
 *
 *  2. **Когда сводку можно закрывать** ([verdict], [settle]). Раньше заход дожидался
 *     всех четырёх ответов до конца бюджета, хотя итог часто ясен раньше: два подменных
 *     адреса из трёх — это уже признак, два настоящих — уже не признак. Контрольный
 *     домен при этом только запрещает: молчащий контроль не подменяет ничего, и ждать
 *     его полный бюджет незачем — прежний код всё равно считал неотвеченный контроль
 *     настоящим, только платил за это секундами.
 *
 *  3. **Сколько признак живёт** ([stands]). Первые секунды на свежем вайфае сводка
 *     мигает: замер 10.08.2026 дал 3 из 3 → 0 из 3 → 3 из 3 подряд. На «0 из 3» автомат
 *     объявлял обычную сеть, поднимал туннель и через пару секунд гасил его обратно —
 *     это и есть «на вайфай зачем-то включает впн». Одна слепая сводка теперь признак
 *     не отменяет: отменяет его только опровержение делом — не прошедший наружу трафик
 *     или подсказка «белый список».
 */
internal object HomeSign {

    /**
     * Сколько признак дома считается стоящим после того, как его видели в последний раз.
     *
     * Мерка взята от серии перепроверок ([AutoMode.BURST_STEPS]): её самый длинный шаг —
     * двадцать секунд, и признак обязан пережить один такой шаг вместе с самим заходом.
     * Больше брать незачем: смена сети стирает память о признаке сразу, а на той же сети
     * дом никуда не девается.
     */
    const val MEMORY_MILLIS = 45_000L

    /**
     * Сколько ждём контрольный домен, когда подменных адресов уже набрано достаточно.
     *
     * Контроль отвечает на один вопрос: не подменяет ли этот резолвер вообще всё подряд.
     * Резолвер, который подменяет всё, отвечает быстро — он местный. Молчание контроля
     * прежний код засчитывал как «настоящий адрес» по истечении всего бюджета; здесь тот
     * же засчёт происходит раньше, и вердикт от этого не меняется — меняется только
     * время до него.
     */
    const val CONTROL_BUDGET_MILLIS = 1_200L

    /** Что ответил контрольный домен. */
    enum class Control {
        /** Ещё не ответил. */
        Waiting,

        /** Настоящий адрес — резолвер подменяет выборочно, как наш роутер. */
        Real,

        /** Подменён и он тоже: это не наш роутер, а что-то, что подменяет всё подряд. */
        Fake,
    }

    /**
     * Может ли эта сеть быть домом.
     *
     * Отказ выносим только там, где уверены: сота и ничего больше. Про сеть без
     * известного транспорта не выдумываем — спрашиваем резолвер, как раньше.
     */
    fun reachable(wifi: Boolean, ethernet: Boolean, cellular: Boolean): Boolean =
        !(cellular && !wifi && !ethernet)

    /**
     * Итог сводки по тем ответам, что уже пришли.
     *
     * @param hits сколько доменов вернули подменный адрес.
     * @param misses сколько вернули настоящий (или не ответили).
     * @param domains сколько доменов спрашивали всего.
     * @param needed сколько совпадений нужно для признака.
     * @return `null` — ответа пока нет, ждём дальше.
     */
    fun verdict(hits: Int, misses: Int, domains: Int, needed: Int, control: Control): Boolean? = when {
        // Подменён и контрольный — это не наш роутер. Дальше смотреть нечего.
        control == Control.Fake -> false
        // До нужного числа совпадений уже не добрать, сколько ни жди.
        domains - misses < needed -> false
        hits >= needed && control == Control.Real -> true
        else -> null
    }

    /**
     * Итог сводки, когда ждать больше нечего: бюджет вышел или контроль исчерпал свой срок.
     * Неотвеченный контроль засчитывается настоящим — ровно как и до правки.
     */
    fun settle(hits: Int, needed: Int, control: Control): Boolean =
        control != Control.Fake && hits >= needed

    /**
     * Стоит ли признак дома прямо сейчас.
     *
     * @param seenNow сводка этого захода дала признак.
     * @param ageMillis сколько прошло с последнего признака на **этой же** сети;
     *   `null` — признака на ней не видели.
     * @param refuted признак опровергнут делом: наружу не прошёл прямой запрос или
     *   определитель сказал «белый список». Опровержение бьёт память, но не свежее
     *   наблюдение: под белым списком дома резолвер отвечает подменными адресами
     *   честно, и врать про это незачем — дом всё равно не объявится, вердикт
     *   складывается выше ([AutoMode.homeVerdict]).
     */
    fun stands(
        seenNow: Boolean,
        ageMillis: Long?,
        refuted: Boolean,
        memoryMillis: Long = MEMORY_MILLIS,
    ): Boolean = when {
        seenNow -> true
        refuted -> false
        ageMillis == null -> false
        else -> ageMillis in 0 until memoryMillis
    }
}
