package io.nekohasekai.sfa.bg

/**
 * Самоподъём службы после смерти процесса.
 *
 * Служба теперь «липкая» (`START_STICKY`): когда система убивает процесс (нехватка памяти,
 * чистка фона прошивкой), она сама поднимает службу заново и зовёт `onStartCommand`
 * **без интента**. До этого служба была `START_NOT_STICKY`, и после смерти процесса
 * туннеля не было, пока процесс не поднимало что-то другое — фоновая работа раз в
 * 15 минут или сам человек (разбор 07.11.2026: окно до десятков минут при открытом
 * трафике).
 *
 * Поднимать ли ядро на таком старте — решает чистая функция [reshit], по трём фактам:
 *  - человек службу включал и не выключал (`Settings.startedByUser`; остановка её стирает);
 *  - служба смогла стать службой переднего плана: на Android 12+ `startForeground()`
 *    из фона может быть отклонён (`ForegroundServiceStartNotAllowedException`), а
 *    фоновую службу система гасит через минуту — поднимать ядро на ней бессмысленно;
 *  - разрешение на VPN на месте: без него подъём кончится аварией, а выдать его
 *    может только человек из окна приложения.
 *
 * Если поднять нельзя, а человек службу хотел — ему уведомление «нажмите, чтобы
 * включить» ([AvtoVozvrat]): тап — действие человека, из него запуск разрешён всегда.
 */
internal object Samopodem {
    enum class Shag {
        /** Поднимать ядро, как по обычной команде. */
        PODNYAT,

        /** Поднять нельзя — позвать человека уведомлением и тихо погасить службу. */
        UVEDOMIT,

        /** Человек службу выключал — система ошиблась, тихо гасим. */
        NICHEGO,
    }

    /**
     * @param hotel человек включал службу и не выключал.
     * @param vPerednemPlane `startForeground()` прошёл.
     * @param vpnRazreshenie разрешение на VPN на месте (или режим без VPN).
     */
    fun reshit(hotel: Boolean, vPerednemPlane: Boolean, vpnRazreshenie: Boolean): Shag = when {
        !hotel -> Shag.NICHEGO
        !vpnRazreshenie -> Shag.UVEDOMIT
        !vPerednemPlane -> Shag.UVEDOMIT
        else -> Shag.PODNYAT
    }
}
