package io.nekohasekai.sfa.bg

import io.nekohasekai.sfa.bg.pult.Pult

/**
 * Сторож транспорта на основном канале: ритм дешёвых проб между полными заходами и
 * счётчик провалов, по которому заход будится раньше срока.
 *
 * Зачем. На основном канале полный заход идёт раз в пять минут, и смерть транспорта
 * (XHTTP встал, узел перестал отвечать) замечалась через минуты: живые отказы
 * соединений будят заход только при двух и более узлах в очереди, шторм отказов — не
 * чаще раза в пять минут. Здесь между заходами идёт короткая проба через закреплённый
 * вход основного узла (мимо селектора, живые соединения не трогаются), и два провала
 * подряд будят полный заход. Решение остаётся за заходом и его задвижкой: проба ничего
 * не переключает, она только зовёт.
 *
 * Почему два, а не один. Одна проба на перегруженном канале может не дождаться ответа
 * (замер 07.08.2026: служебный отклик 2-9 с под нагрузкой); будить по одному провалу
 * значит гонять полный заход на каждый чих. Два подряд за полминуты-минуту — уже не чих.
 *
 * Батарея. Пауза [MIN_MILLIS]..[MAX_MILLIS] с экраном, вдвое длиннее с выключенным
 * экраном ([slice]); в дозе проба не ходит вовсе (решает звонящий по
 * `PowerManager.isDeviceIdleMode`); без сети не ходит тоже.
 *
 * Без Android внутри — чтобы ритм и счётчик можно было проверить тестом.
 */
internal object TransportWatch {
    /** Нижняя граница паузы между пробами при включённом экране. */
    const val MIN_MILLIS = 30_000L

    /** Верхняя граница паузы при включённом экране. */
    const val MAX_MILLIS = 60_000L

    /** Во сколько раз длиннее шаг при выключенном экране. */
    const val SCREEN_OFF_FACTOR = 2L

    /** Сколько провалов подряд будят заход. */
    const val FAILS_TO_WAKE = 2

    /**
     * Сколько ждать до следующей пробы.
     *
     * @param left сколько осталось до полного захода — его не перешагиваем.
     * @param roll случайная пауза; за границы не выпускаем.
     * @param screenOn экран включён; выключен — шаг вдвое длиннее.
     */
    fun slice(left: Long, roll: Long, screenOn: Boolean): Long {
        val min = Pult.long("avtomat.transport_min_millis", MIN_MILLIS)
        val max = Pult.long("avtomat.transport_max_millis", MAX_MILLIS).coerceAtLeast(min)
        val base = roll.coerceIn(min, max)
        val step = if (screenOn) base else base * SCREEN_OFF_FACTOR
        return minOf(left, step)
    }

    /**
     * Счётчик провалов подряд. Удача обнуляет; несостоявшийся замер (вход не принял
     * соединение — ядро пересобрано) не считается ни тем, ни другим.
     */
    class Schetchik(private val failsToWake: () -> Int = { Pult.int("avtomat.transport_fails_to_wake", FAILS_TO_WAKE) }) {
        var fails: Int = 0
            private set

        fun ok() {
            fails = 0
        }

        /** @return true — провалов подряд набралось, заход пора будить (счётчик при этом обнуляется). */
        fun fail(): Boolean {
            fails++
            if (fails < failsToWake().coerceAtLeast(1)) return false
            fails = 0
            return true
        }

        fun reset() {
            fails = 0
        }
    }
}
