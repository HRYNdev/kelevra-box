package io.nekohasekai.sfa.bg

/**
 * Приглядка дома: чем режется пауза между полными заходами и что считается поводом
 * будить заход раньше срока.
 *
 * Зачем вообще. Дома туннель погашен, ядра нет, своих исходящих нет — и об ограничении,
 * наступившем **без смены сети**, сказать некому: ломаться нечему. Остаётся ждать либо
 * своего таймера (полный заход дома — пять минут), либо того, что система сама снимет
 * с сети признак VALIDATED и разбудит нас через [DefaultNetworkListener]. Замер на стенде
 * белого списка: ограничение включено в 15:08:12, автомат проснулся в 15:10:56
 * (по снятому VALIDATED), режим распознан в 15:11:14. Две минуты сорок четыре секунды
 * телефон считал, что дома, при мёртвой связи.
 *
 * Почему проба, а не более частый полный заход. Полный заход дома стоит четырёх запросов
 * к резолверу плюс до двух прямых запросов наружу и переписывает весь реестр путей. Гонять
 * его раз в минуту значит впятеро умножить всё это ради одного-единственного вопроса —
 * **уходит ли ещё наружу трафик**. Сам вопрос стоит одного короткого запроса, вот его
 * и задаём, а ритм заходов оставляем прежним.
 *
 * Почему трафик, а не резолвер. Резолвер дешевле, и признак дома снимается именно им —
 * но под ограничением он продолжает отвечать. Домашний (он же операторский) резолвер
 * разрешён во всех трёх профилях стенда `tools/android/whitelist-on.sh`, и подменные
 * адреса от роутера приходят как ни в чём не бывало. То есть DNS-проба не сдвинулась бы
 * вовсе, а чиним мы ровно её отставание. Умирает наружный трафик — его и спрашиваем.
 *
 * Цена. Пауза [MIN_MILLIS]..[MAX_MILLIS], в среднем 55 секунд, то есть около
 * [peeksPerHour] проб в час — и только дома, где сеть по определению вайфай: домом мы
 * считаем сеть, в которой обход делает наш собственный роутер. Для сравнения, приглядка
 * из комнаты ходит каждые 20-40 секунд, то есть вдвое чаще и по мобильной сети. Полных
 * заходов при этом не прибавляется ни одного: их по-прежнему двенадцать в час.
 *
 * Чаще нельзя: раз в десять секунд — это триста шестьдесят пробуждений радио в час ради
 * события, которое случается несколько раз в год. Реже нельзя: полторы минуты вслепую —
 * это уже не «порядка минуты», ради которой всё и затевалось.
 *
 * Без Android внутри — чтобы ритм и повод будить можно было проверить, а не пересказать.
 */
internal object HomeWatch {
    /** Нижняя граница паузы между пробами. */
    const val MIN_MILLIS = 40_000L

    /** Верхняя граница паузы между пробами. Она же — худшее время реакции. */
    const val MAX_MILLIS = 70_000L

    /**
     * Сколько ждать до следующей пробы.
     *
     * Интервал не ровный намеренно: ровный означал бы метроном, а метроном — узнаваемый
     * след. Остаток полного круга не перешагиваем: иначе проба сдвигала бы сам заход,
     * то есть чинила бы одно отставание, заводя другое.
     *
     * @param left сколько осталось до полного захода.
     * @param roll случайная величина паузы. Выводить её за границы незачем, но и верить
     *   вызывающему на слово тут не за что.
     */
    fun slice(left: Long, roll: Long): Long = minOf(left, roll.coerceIn(MIN_MILLIS, MAX_MILLIS))

    /**
     * Будить ли полный заход по итогу пробы.
     *
     * Одного неудачного запроса достаточно, и «не дёргаться» это не нарушает: проба
     * ничего не решает и ничего не переключает — она только зовёт заход. Решение
     * остаётся за [AutoModeGate] с его подтверждениями. Цена ошибки тут — один лишний
     * заход, цена осторожности — ещё минута вслепую.
     */
    fun wake(trafficFlows: Boolean): Boolean = !trafficFlows

    /** Сколько проб в час даёт этот ритм. Цена приглядки, записанная числом, а не словом. */
    fun peeksPerHour(): Double = 3_600_000.0 / ((MIN_MILLIS + MAX_MILLIS) / 2.0)
}
