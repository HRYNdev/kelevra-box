    /**
     * Физическая сеть — та, что под нашим туннелем. Именно её резолвер и её маршруты
     * отвечают на вопрос «что вокруг», поэтому VPN-сети отбрасываем.
     *
     * Спрашиваем в первую очередь **систему**, какую сеть она сама считает основной.
     * Перебор всех сетей — только запасной путь, и не зря: когда телефон возвращается
     * домой, мобильная сеть не исчезает в ту же секунду, а висит рядом с вайфаем ещё
     * до полуминуты, тоже проверенная. Перебор в такой момент честно находит проверенную
     * сеть — только не ту: пробы уходили в мобильную, домашний резолвер никто не
     * спрашивал, и «дома» не наступало, пока мобильную не погасят. Система же знает,
     * какая сеть стала основной, сразу.
     */
    private fun physicalNetwork(): Network? = systemDefault() ?: anyPhysical()

    /** Сеть, которую основной считает система. null — она VPN или её нет. */
    private fun systemDefault(): Network? {
        DefaultNetworkMonitor.defaultNetwork?.takeIf(::physical)?.let { return it }
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
            runCatching { Application.connectivity.activeNetwork }.getOrNull()
                ?.takeIf(::physical)
                ?.let { return it }
        }
        return null
    }

    @Suppress("DEPRECATION")
    private fun anyPhysical(): Network? {
        val manager = Application.connectivity
        val networks = runCatching { manager.allNetworks }.getOrElse { return null }
        var fallback: Network? = null
        for (network in networks) {
            val caps = runCatching { manager.getNetworkCapabilities(network) }.getOrNull() ?: continue
            if (caps.hasTransport(NetworkCapabilities.TRANSPORT_VPN)) continue
            if (!caps.hasCapability(NetworkCapabilities.NET_CAPABILITY_INTERNET)) continue
            // Проверенная системой сеть лучше просто присутствующей: вайфай без интернета
            // (портал в кафе) не должен выглядеть рабочей сетью.
            if (caps.hasCapability(NetworkCapabilities.NET_CAPABILITY_VALIDATED)) return network
            if (fallback == null) fallback = network
        }
        return fallback
    }

    /** Годится ли сеть на роль «того, что вокруг»: не наш туннель и вообще про интернет. */
    private fun physical(network: Network): Boolean {
        val caps = runCatching { Application.connectivity.getNetworkCapabilities(network) }.getOrNull()
            ?: return false
        if (caps.hasTransport(NetworkCapabilities.TRANSPORT_VPN)) return false
        return caps.hasCapability(NetworkCapabilities.NET_CAPABILITY_INTERNET)
    }

    private fun validated(network: Network): Boolean =
        runCatching { Application.connectivity.getNetworkCapabilities(network) }.getOrNull()
            ?.hasCapability(NetworkCapabilities.NET_CAPABILITY_VALIDATED) == true

    /** Как назвать сеть в логе: без этого «сеть сменилась» ничего не говорит. */
    private fun describe(network: Network?): String {
        if (network == null) return "сети нет"
        val caps = runCatching { Application.connectivity.getNetworkCapabilities(network) }.getOrNull()
            ?: return "$network (о ней ничего не известно)"
        val transport = when {
            caps.hasTransport(NetworkCapabilities.TRANSPORT_WIFI) -> "вайфай"
            caps.hasTransport(NetworkCapabilities.TRANSPORT_CELLULAR) -> "мобильная"
            caps.hasTransport(NetworkCapabilities.TRANSPORT_ETHERNET) -> "кабель"
            caps.hasTransport(NetworkCapabilities.TRANSPORT_VPN) -> "VPN"
            else -> "какая-то"
        }
        val checked = if (caps.hasCapability(NetworkCapabilities.NET_CAPABILITY_VALIDATED)) {
            "проверена"
        } else {
            "ещё не проверена"
        }
        return "$transport $network, $checked"
    }

    /**
     * Снимок связи словами: интерфейс, свой адрес, резолверы, шлюз и уровень сигнала.
     *
     * Всё это берётся без единого нового разрешения: [LinkProperties] отдаёт система
     * любому, `ACCESS_WIFI_STATE` в манифесте стоит с самого начала. Имени сети (SSID) и
     * точки (BSSID) здесь нет намеренно: с Android 10 их отдают только с разрешением на
     * геолокацию, а его семья не выдаст. Роуминг ловится не по имени точки, а по тому,
     * что при переходе меняются шлюз, резолверы и уровень сигнала.
     */
    @Suppress("DEPRECATION")
    private fun linkNote(network: Network?): String {
        if (network == null) return "сети нет"
        val link = runCatching { Application.connectivity.getLinkProperties(network) }.getOrNull()
        val caps = runCatching { Application.connectivity.getNetworkCapabilities(network) }.getOrNull()
        val parts = mutableListOf<String>()
        parts += "интерфейс ${link?.interfaceName ?: "?"}"
        val own = link?.linkAddresses?.mapNotNull { it.address?.hostAddress }?.filter { !it.contains(':') }
        parts += "адрес ${own?.joinToString(",").orEmpty().ifBlank { "?" }}"
        parts += "резолверы ${
            link?.dnsServers?.mapNotNull { it.hostAddress }?.joinToString(",").orEmpty().ifBlank { "нет" }
        }"
        val gateway = runCatching {
            link?.routes?.filter { it.isDefaultRoute }?.mapNotNull { it.gateway?.hostAddress }
        }.getOrNull().orEmpty()
        if (gateway.isNotEmpty()) parts += "шлюз ${gateway.joinToString(",")}"
        if (caps?.hasTransport(NetworkCapabilities.TRANSPORT_WIFI) == true) {
            runCatching {
                val info = Application.wifiManager.connectionInfo
                if (info != null && info.rssi > -127) {
                    // Огру***ем до пяти децибел нарочно: сырой уровень дрожит на единицу
                    // каждую секунду, и снимок «изменился» превращался бы в поток. Уход
                    // на другую точку — это скачок на 10-20 дБм, он сквозь огрубление виден.
                    parts += "сигнал ${info.rssi / 5 * 5} дБм"
                    // Частота — самый дешёвый признак смены точки: репитер держит 5 ГГц,
                    // роутер отдаёт 2.4, и переход между ними виден без разрешений.
                    if (info.frequency > 0) parts += "частота ${info.frequency} МГц"
                }
            }
        }
        return parts.joinToString(", ")
    }

    /** Пишет снимок связи, только когда он изменился: одинаковых строк в журнале не копим. */
    private fun noteLink(network: Network?, why: String) {
        val note = linkNote(network)
        if (note == lastLinkNote) return
        lastLinkNote = note
        Log.i(TAG, "связь ($why): $note")
    }

    /**
     * Начало и конец молчания резолверов — отдельными строками, с длительностью.
     *
     * Без них разбор 28.08.2026 состоял в том, чтобы вручную складывать время между
     * строками из четырёх источников сразу. «Резолверы молчали 407 с» — это ровно тот
     * факт, ради которого разбор и затевался, и добыть его больше неоткуда: интернет
     * при этом живой, сеть та же, Android ничего не сообщает.
     */
    private fun noteDnsSilence(network: Network, silentNow: Boolean) {
        val now = SystemClock.elapsedRealtime()
        if (silentNow) {
            if (dnsSilentSince != 0L) return
            dnsSilentSince = now
            Log.w(TAG, "резолверы сети замолчали (интернет при этом может быть живым): ${linkNote(network)}")
        } else if (dnsSilentSince != 0L) {
            Log.i(TAG, "резолверы сети отвечают снова — молчали ${(now - dnsSilentSince) / 1000} с")
            dnsSilentSince = 0L
        }
    }

    /**
     * Сводка захода: что видели, что решили и на чём стоим.
     *
     * Одна строка на заход, и та не повторяется, пока не изменилась (или пока не прошло
     * [ROUND_NOTE_REPEAT_MILLIS]). Ритм захода — от 12 секунд в поиске до пяти минут в
     * покое, так что журнал этим не захлебнётся, а разбор перестаёт быть догадкой: до
     * этого вердикт «не дома» на сети без признака DNS не писался вообще никогда, и
     * «почему включился туннель» приходилось выводить из соседних строк.
     */
    private fun noteRound(observed: Situation) {
        val confirmations = if (gate.pending) ", подтверждений ${gate.hits} из ${gate.needed}" else ""
        // Наборы правил решают, что вообще уходит в туннель. Недокачанные наборы и есть
        // самая частая изнанка жалобы «подключено, а сайты не грузятся»: путь живой,
        // трафик идёт, а нужные домены в него не заворачиваются.
        val rules = RuleSetCache.state.value
        val note = "заход: $observationNote; наборы правил ${rules.ready} из ${rules.total} → " +
            "вижу «${name(observed)}», стою на «${name(gate.current)}»$confirmations"
        val now = SystemClock.elapsedRealtime()
        if (note == lastRoundNote && now - lastRoundNoteAt < ROUND_NOTE_REPEAT_MILLIS) return
        lastRoundNote = note
        lastRoundNoteAt = now
        Log.i(TAG, note)
    }

    /**
     * Дома ли мы: спрашиваем системный резолвер физической сети про домены, которые
     * роутер точно заворачивает, и смотрим, попал ли ответ в подменный диапазон.
     */
    private fun homeBypass(network: Network): HomeSign.Sign {
        val pool = Executors.newFixedThreadPool(HOME_DOMAINS.size + 1)
        try {
            val answers = ExecutorCompletionService<Pair<String, HostAnswer>>(pool)
            for (host in HOME_DOMAINS + HOME_CONTROL) {
                // Ответ приходит вместе с именем, и сам вопрос никогда не бросает: иначе
                // на сорвавшейся пробе было бы не понять, чей это ответ. Сорвался — это
                // [HostAnswer.Silent], а не «настоящий адрес»: разница между «не узнали»
                // и «не дома» и есть смысл всей этой правки.
                answers.submit { host to runCatching { askHost(network, host) }.getOrDefault(HostAnswer.Silent) }
            }
            val startedAt = SystemClock.elapsedRealtime()
            val deadline = startedAt + DNS_BUDGET_MILLIS
            var hits = 0
            var misses = 0
            var silent = 0
            var control = HomeSign.Control.Waiting
            var sign: HomeSign.Sign? = null
            var answered = 0
            // Что ответил каждый домен по отдельности. Без этого «промолчали 3 из 3»
            // не отличить от «промолчал один и тот же резолвер на всех трёх»: первое
            // бывает при белом списке, второе — при протухшем пути до резолвера.
            val details = mutableListOf<String>()
            // Разбираем ответы по мере прихода и закрываем сводку, как только итог ясен.
            // Раньше заход дожидался всех четырёх до конца бюджета, и один задумавшийся
            // домен стоил 2.5 секунды всему решению.
            while (answered < HOME_DOMAINS.size + 1) {
                // Ждём ровно столько, сколько ещё может что-то изменить: пока не хватает
                // совпадений — весь бюджет, а когда их уже хватает и ждём только контроль —
                // его короткий срок. Молчащий контроль и раньше засчитывался настоящим.
                val until = if (hits >= HOME_HITS && control == HomeSign.Control.Waiting) {
                    minOf(deadline, startedAt + HomeSign.CONTROL_BUDGET_MILLIS)
                } else {
                    deadline
                }
                val left = until - SystemClock.elapsedRealtime()
                if (left <= 0) break
                val done = runCatching { answers.poll(left, TimeUnit.MILLISECONDS) }.getOrNull() ?: break
                answered++
                val (host, answer) = runCatching { done.get() }.getOrNull() ?: continue
                details += "$host=${
                    when (answer) {
                        HostAnswer.Fake -> "подменный"
                        HostAnswer.Real -> "настоящий"
                        HostAnswer.Silent -> "молчит"
                    }
                }"
                when {
                    host == HOME_CONTROL -> control = when (answer) {
                        HostAnswer.Fake -> HomeSign.Control.Fake
                        HostAnswer.Real -> HomeSign.Control.Real
                        HostAnswer.Silent -> HomeSign.Control.Silent
                    }

                    answer == HostAnswer.Fake -> hits++
                    answer == HostAnswer.Real -> misses++
                    else -> silent++
                }
                val decided = HomeSign.verdict(hits, misses, silent, HOME_DOMAINS.size, HOME_HITS, control)
                if (decided != null) {
                    sign = decided
                    break
                }
            }
            // Вердикт не сложился — значит вышли по бюджету. Те, чьего ответа так и не
            // дождались, идут в молчуны: это тоже «не узнали», а не «настоящий адрес».
            // Контроль среди них считается отдельно, он в число доменов не входит.
            if (sign == null) {
                val pending = (HOME_DOMAINS.size + 1) - answered
                val controlPending = if (control == HomeSign.Control.Waiting) 1 else 0
                silent += (pending - controlPending).coerceAtLeast(0)
            }
            val result = sign ?: HomeSign.settle(hits, misses, silent, HOME_HITS, control)
            // Говорим ровно то, что узнали: это признак, а не вердикт. Вердикт «дома»
            // складывается выше, из признака и прошедшего наружу трафика, — и лог,
            // который писал здесь «→ дома», врал ровно в той обстановке, ради которой
            // всё и затевалось.
            val resolvers = runCatching {
                Application.connectivity.getLinkProperties(network)?.dnsServers?.mapNotNull { it.hostAddress }
            }.getOrNull().orEmpty()
            Log.i(
                TAG,
                "признак дома по DNS в сети «${describe(network)}»: подменных $hits из ${HOME_DOMAINS.size}, " +
                    "настоящих $misses, промолчали $silent, контрольный $HOME_CONTROL $control, " +
                    "спрашивали ${resolvers.joinToString(",").ifBlank { "резолверов нет" }}, " +
                    "по доменам [${details.joinToString(", ")}], " +
                    "за ${SystemClock.elapsedRealtime() - startedAt} мс → " +
                    when (result) {
                        HomeSign.Sign.Yes -> "признак есть"
                        HomeSign.Sign.No -> "признака нет"
                        HomeSign.Sign.Unknown -> "не узнали (резолверы молчат)"
                    },
            )
            return result
        } finally {
            pool.shutdownNow()
        }
    }

    /**
     * Доделана ли сеть настолько, чтобы её ответам можно было верить.
     *
     * Android объявляет вайфай доступным раньше, чем на нём заработает всё остальное:
     * адрес по DHCP, резолверы, проверка интернета. Проба в эту секунду отвечает честно —
     * но про недоделанную сеть, и раньше этот ответ уезжал в обычный ритм на пять минут.
     * Здесь мы не ждём и не спим: заход идёт как шёл, просто его итог не считается
     * основанием закрыть серию перепроверок.
     */
    private fun networkMatured(network: Network): Boolean = runCatching {
        val validated = validated(network)
        val resolvers = Application.connectivity.getLinkProperties(network)?.dnsServers.orEmpty()
        validated && resolvers.isNotEmpty()
    }.getOrElse { true }

    /**
     * Может ли эта сеть быть домом. Про сеть, транспорт которой не выяснить, отказа
     * не выдумываем: спрашиваем резолвер, как раньше.
     */
    private fun homeReachable(network: Network): Boolean {
        val caps = runCatching { Application.connectivity.getNetworkCapabilities(network) }.getOrNull()
            ?: return true
        return HomeSign.reachable(
            wifi = caps.hasTransport(NetworkCapabilities.TRANSPORT_WIFI),
            ethernet = caps.hasTransport(NetworkCapabilities.TRANSPORT_ETHERNET),
            cellular = caps.hasTransport(NetworkCapabilities.TRANSPORT_CELLULAR),
        )
    }

    /**
     * Стоит ли пускать прямую пробу вперёд сводки резолвера.
     *
     * Только там, где её ответ почти наверняка понадобится: сразу после смены сети
     * (серия перепроверок идёт) и когда мы уже стоим дома. В обычном ритме на чужой
     * сети параллельная проба была бы лишним запросом наружу каждым заходом — а число
     * запросов мы не увеличиваем.
     */
    private fun speculateHomeTraffic(): Boolean = burst.active || gate.current == Situation.Home

    /**
     * Пускает прямую пробу отдельным потоком и отдаёт способ дождаться её итога.
     * Пока она идёт, заход успевает спросить резолвер.
     */
    private fun aheadHomeTraffic(network: Network): () -> Boolean? {
        val answer = AtomicReference<Boolean?>(null)
        val worker = Thread(
            { answer.set(runCatching { homeCarriesTraffic(network) }.getOrNull()) },
            "home-traffic",
        ).apply {
            isDaemon = true
            start()
        }
        // Своего срока тут нет и не надо: проба ограничена собственными таймаутами,
        // а лишний срок поверх них превратил бы медленный ответ в выдуманный отказ.
        return {
            runCatching { worker.join() }
            answer.get()
        }
    }

    /** Признак дома видели прямо сейчас — запоминаем вместе с сетью, на которой это было. */
    private fun rememberHomeSign(network: Network) {
        homeSignNetwork = networkKey(network)
        homeSignAt = SystemClock.elapsedRealtime()
    }

    /** Признак опровергнут делом или относится к другой сети — держаться за него не на чем. */
    private fun forgetHomeSign() {
        homeSignNetwork = null
        homeSignAt = 0L
    }

    /** Сколько прошло с последнего признака на **этой** сети; `null` — на ней его не видели. */
    private fun homeSignAge(network: Network): Long? {
        if (homeSignAt == 0L || homeSignNetwork != networkKey(network)) return null
        return SystemClock.elapsedRealtime() - homeSignAt
    }

    /**
     * Отпечаток сети: тот же вайфай остаётся тем же, даже если система выдала ему
     * новый номер.
     *
     * Помнить признак дома по объекту [Network] оказалось нельзя. Замер на живом
     * телефоне 10.08.2026: четыре переключения вайфая за минуту, на каждом Android
     * выдаёт новый номер (1025 → 1026), память о доме обнуляется, и на возврате домой
     * автомат успевает поднять туннель на полторы секунды, прежде чем понять, что мы
     * дома. Со стороны это и есть «то включается, то выключается».
     *
     * Отпечаток берём из того, что у домашней сети постоянно и не требует разрешений:
     * транспорт, адреса её резолверов и наш адрес с длиной префикса. SSID подошёл бы
     * лучше, но с Android 10 за него спрашивают разрешение на местоположение — платить
     * им за узнавание своей же сети не станем.
     */
    private fun networkKey(network: Network): String = runCatching {
        val caps = Application.connectivity.getNetworkCapabilities(network)
        val link = Application.connectivity.getLinkProperties(network)
        val transport = when {
            caps == null -> "?"
            caps.hasTransport(NetworkCapabilities.TRANSPORT_WIFI) -> "wifi"
            caps.hasTransport(NetworkCapabilities.TRANSPORT_CELLULAR) -> "cell"
            else -> "other"
        }
        // Только транспорт и резолверы сети. Свой адрес в отпечаток класть нельзя:
        // при переподключении к тому же вайфаю DHCP выдаёт другой, отпечаток «меняется»,
        // и память о доме слетает ровно там, ради чего написана. Проверено на телефоне
        // 10.08.2026: с адресом в ключе туннель всё равно подскакивал на каждом возврате.
        val dns = link?.dnsServers?.mapNotNull { it.hostAddress }?.sorted()?.joinToString(",").orEmpty()
        "$transport|$dns"
    }.getOrElse { "network-${network.hashCode()}" }

    /**
     * Уходит ли через домашний путь трафик наружу **на самом деле**.
     *
     * Это вторая половина вердикта «дома», и без неё первая ничего не стоила. Признак
     * по DNS говорит ровно одно: нам отвечает домашний резолвер. Он отвечает так же и
     * тогда, когда наружу не проходит ни один пакет, — и ровно так автомат гасил туннель
     * в сети с белым списком, показывая человеку «Дома, обход на роутере» при мёртвой
     * связи (стенд `tools/android/whitelist-on.sh`, 08.08.2026).
     *
     * Проба идёт [HonestProbe.measureDirect]: тот же запрос, что и для остальных путей,
     * только напрямую — дома посредника нет, туннель погашен. Одной привязки сокета к
     * физической сети для этого мало (правило per-uid для VPN стоит выше неё), поэтому
     * сокет ещё и защищён от нашего же tun — [ProbeSocket]. Без защиты при поднятом
     * туннеле проба меряла туннель, то есть подтверждала дом сама себе, и осечка вердикта
     * становилась незакрывающейся: поднятый туннель не давал ей разойтись.
     */
    private fun homeCarriesTraffic(network: Network): Boolean? {
        lastHomeLatencyMs = null
        var measured = false
        repeat(HOME_TRAFFIC_TRIES) { attempt ->
            val measurement = HonestProbe.measureDirect(network, "дома")
            if (measurement.live) {
                lastHomeLatencyMs = measurement.latencyMs
                // Прямой запрос наружу дошёл и вернулся. Цель пробы в белом списке
                // оператора не значится, значит белого списка вокруг нет — и подсказку
                // об обратном (если она ещё жива) держать больше не на чем.
                NetworkModeDetector.forget("прямой трафик наружу проходит")
                return true
            }
            // Замер, который не состоялся (имя цели не резолвится — на свежем вайфае это
            // норма первых секунд), отказом не считается. Раньше он приходил сюда тем же
            // «мёртв», что и настоящее «SYN ушёл, ответа нет», стирал память о доме и
            // отправлял человека в туннель на пять минут.
            if (measurement.measured) measured = true
            Log.i(TAG, "дом трафиком не подтверждён (попытка ${attempt + 1}): $measurement")
        }
        return if (measured) false else null
    }

    /**
     * Вердикт «мы дома». Вынесен отдельно и без единого обращения к Android: главное
     * утверждение — «признак DNS без трафика домом не считается» — должно проверяться
     * тестом, а не пересказом.
     *
     * @param dnsSign домашний резолвер отдал подменные адреса.
     * @param trafficConfirmed через домашний путь реально прошёл запрос и вернулся ответ.
     *   `null` — не проверяли (в том числе когда проверять было незачем).
     * @param hint что говорит определитель режима сети. [NetworkMode.Whitelist] отменяет
     *   дом при любых признаках: под белым списком подменные адреса ничего не значат.
     */
    internal fun homeVerdict(dnsSign: Boolean, trafficConfirmed: Boolean?, hint: NetworkMode): Boolean = when {
        hint == NetworkMode.Whitelist -> false
        !dnsSign -> false
        // Не подтвердилось — не объявляем. «Не проверяли» это тоже «не подтвердилось»:
        // домом считается только то, через что доказанно ходит трафик.
        else -> trafficConfirmed == true
    }

    /** Почему домом не считаем — человеку и в лог. */
    private fun homeReason(dnsSign: Boolean, trafficConfirmed: Boolean?, hint: NetworkMode): String = when {
        hint == NetworkMode.Whitelist -> WHITELIST_REASON
        !dnsSign -> "подменных адресов нет"
        trafficConfirmed == false -> "подменные адреса есть, но наружу не проходит"
        else -> "дом не подтверждён трафиком"
    }

    /**
     * Считается ли обстановка «сломанной» настолько, чтобы звать определитель режима сети.
     *
     * Замер стоит до полутора десятков секунд прямо посреди захода (TCP, TLS, короткая
     * передача), и в первые секунды после смены сети он покупает ответ, который ничего
     * не решает: свежий вайфай честно не пропускает наружу первый запрос, а «белый список»
     * так не выглядит — он не наступает вместе с подключением к сети. Поэтому пока сеть
     * настраивается, поводом остаётся только уже провалившийся основной канал: под белым
     * списком он проваливается тем же заходом, и определитель отстаёт ровно на один шаг
     * серии (секунду), а не пропускается.
     *
     * @param homeMismatch дом по DNS есть, а трафик через него не идёт.
     * @param mainFailed основной канал уже не поднялся хотя бы раз.
     * @param settling идёт серия перепроверок после смены сети.
     */
    internal fun brokenEnough(homeMismatch: Boolean, mainFailed: Boolean, settling: Boolean): Boolean =
        if (settling) mainFailed else homeMismatch || mainFailed

    /**
     * Можно ли закрывать серию перепроверок после смены сети.
     *
     * Раньше условие было из двух частей: заход ничего не поменял и подтверждений никто
     * не ждёт. Беда в том, что **устойчиво неверный вердикт выглядит точно так же, как
     * устоявшаяся обстановка**: серия 1/3/8/20 секунд обрывалась на первом шаге, а
     * следующая проверка приходила через пять минут. Именно это описано в жалобе
     * 14.08.2026: дома при живом обходе на роутере поднимается туннель и висит, пока
     * человек не передёрнет вайфай руками.
     *
     * Третья часть закрывает дыру: заход, который ничего не узнал (резолверы промолчали,
     * замер не состоялся, сеть не доделана), серию не закрывает. Он не считается ни
     * верным, ни неверным — он просто не считается.
     *
     * @param changed заход сменил обстановку.
     * @param pending идёт набор подтверждений.
     * @param confident этому заходу есть на чём стоять ([observationConfident]).
     */
    internal fun burstClosable(changed: Boolean, pending: Boolean, confident: Boolean): Boolean =
        !changed && !pending && confident

    /**
     * Стоит ли тратить замер режима сети.
     *
     * Определитель дорог: до двух соединений, TLS и десятки килобайт — и, что важнее,
     * сам паттерн повторяющихся проб различим снаружи. Поэтому спрашиваем его не по
     * расписанию, а по поводу: пока всё работает, режим сети знать незачем.
     *
     * @param broken что-то уже не сходится: дом по DNS без трафика или провалившийся канал.
     * @param cachedAgeMillis сколько лет вердикту про **эту** сеть; `null` — на ней не мерили.
     * @param nodeAnswers узел основного канала только что принял соединение. Из всех
     *   вердиктов определителя на решения влияет один — [NetworkMode.Whitelist], — а он
     *   этим фактом уже опровергнут: под белым списком узел недостижим. Спрашивать после
     *   такого значит платить двумя соединениями с TLS за ответ, который у нас есть.
     */
    internal fun askDetector(
        broken: Boolean,
        cachedAgeMillis: Long?,
        nodeAnswers: Boolean = false,
    ): Boolean = when {
        !broken -> false
        nodeAnswers -> false
        cachedAgeMillis == null -> true
        else -> cachedAgeMillis >= HINT_TTL_MILLIS
    }

    /** Свеж ли довод «узел отвечает». */
    private fun nodeAnswers(): Boolean = nodeAnsweredAt != 0L &&
        SystemClock.elapsedRealtime() - nodeAnsweredAt < NODE_ANSWER_TRUST_MILLIS

    /**
     * Узел принял соединение. Это не «канал работает» — до трафика ещё далеко, — но это
     * уже доказательство, что вокруг не белый список, и подсказку об обратном оно
     * опровергает делом.
     */
    private fun nodeAnswered(reason: String) {
        nodeAnsweredAt = SystemClock.elapsedRealtime()
        NetworkModeDetector.forget(reason)
    }

    /** Подсказка про эту сеть, пока она свежая. Ничего не меряет. */
    private fun cachedHint(network: Network): NetworkMode {
        val report = NetworkModeDetector.reportFor(network) ?: return NetworkMode.Unknown
        val age = System.currentTimeMillis() - report.atMillis
        if (age !in 0 until HINT_TTL_MILLIS) return NetworkMode.Unknown
        return report.mode
    }

    /** Сколько лет вердикту про эту сеть; `null` — на ней не мерили ни разу. */
    private fun hintAge(network: Network): Long? =
        NetworkModeDetector.reportFor(network)?.let { System.currentTimeMillis() - it.atMillis }

    /**
     * Спросить определитель режима сети. Замер идёт по той же физической сети, что и
     * остальные пробы захода, — иначе вердикт был бы про другое окружение.
     *
     * Заход автомата живёт в своём потоке и никуда не спешит, поэтому ждём ответа прямо
     * здесь: решение этого захода без него неполное.
     */
    private fun askNetworkMode(network: Network): NetworkMode = runCatching {
        val report = runBlocking { NetworkModeDetector.detect(force = true, network = network) }
        Log.i(TAG, "подсказка о сети: ${report.mode} — ${report.note} (${report.tookMillis} мс)")
        report.mode
    }.getOrElse {
        Log.w(TAG, "режим сети определить не вышло: ${it.message}")
        NetworkMode.Unknown
    }

    /** Что резолвер сети сказал про одно имя. */
    private enum class HostAnswer {
        /** Адрес подменный: имя заворачивает тот, кто нам отвечает. */
        Fake,

        /** Адрес настоящий (или записи нет вовсе) — подмены на этом имени нет. */
        Real,

        /** Ответа не было. Ни то, ни другое: молчание ничего не доказывает. */
        Silent,
    }

    private fun askHost(network: Network, host: String): HostAnswer =
        when (val answer = HomeProbe.ask(network, host, DNS_BUDGET_MILLIS)) {
            is HomeProbe.Answer.Silent -> HostAnswer.Silent
            is HomeProbe.Answer.Addresses -> {
                val fake = answer.addresses.any { address ->
                    val bytes = address.address
                    if (bytes.size != 4) return@any false
                    var value = 0L
                    for (b in bytes) value = (value shl 8) or (b.toLong() and 0xFF)
                    value in FAKE_IP_FIRST..FAKE_IP_LAST
                }
                if (fake) HostAnswer.Fake else HostAnswer.Real
            }
        }

    /**
     * Работает ли основной канал. Две пробы, и вторая — главная.
     *
     *  1. **Порт.** TCP-соединение до адреса узла. Дешёвое, одно RTT, и закрывает самый
     *     частый случай: при белом списке адрес недостижим на уровне маршрутизации,
     *     соединение не встаёт вообще. Порт молчит — дальше смотреть незачем.
     *  2. **Трафик.** Запрос через локальный вход самого sing-box ([ProxyProbe]).
     *     Нужна потому, что ТСПУ душит не установку соединения, а транспорт: порт
     *     ответит, а данные не пойдут — и одной первой пробы автомат бы не заметил.
     *
     * Проба идёт общими маршрутами, то есть через тот выход, который выбран прямо сейчас.
     * Значит, спрашивать «жив ли основной» ею можно только когда выбран основной — этим
     * и занимается [probeThroughMain].
     *
     * Исключение — когда мы уже стоим в комнате ([inRoom]). Там первая проба перестаёт
     * быть достаточной: 11.08.2026 хозяин просидел в комнате 47 минут, хотя ядро всё это
     * время видело основной канал живым (166-308 мс, десять замеров подряд), а выбор
     * выхода за весь день не менялся ни разу — то есть до второй пробы автомат не
     * доходил вовсе. Молчание одного рукопожатия — слишком слабый довод, чтобы держать
     * человека на медленном пути: в комнате спрашиваем канал целиком, даже если адрес
     * узла молчит. Стоит это одну пробу раз в [ROUND_ROOM_MILLIS], и платим мы её
     * только внутри комнаты.
     */
    private fun mainWorks(network: Network, host: Host, inRoom: Boolean = false): Boolean {
        lastMainProbe = null
        val endpoints = layout.mainEndpoints
        val portOpen = if (endpoints.isEmpty()) {
            // Раскладку не поняли — не выдумываем отказ: гнать всех в комнату из-за
            // непрочитанного конфига хуже, чем не заметить белый список.
            null
        } else {
            anyConnects(network, endpoints, TCP_TIMEOUT_MILLIS).also { open ->
                Log.i(
                    TAG,
                    if (open) {
                        "основной канал: адрес узла принимает соединение"
                    } else {
                        "основной канал: ни один из ${endpoints.size} адресов не отвечает"
                    },
                )
                if (open) nodeAnswered("узел основного канала принял соединение")
            }
        }
        // Узел молчит — приглядке есть что искать. Отозвался (или адресов мы не знаем) —
        // искать нечего.
        peekWanted = portOpen == false
        if (portOpen == false && !inRoom) {
            return noteMain(mainVerdict(portOpen = false, trafficFlows = null), portOpen = false)
        }
        if (portOpen == false) {
            Log.i(TAG, "основной канал: адрес узла молчит, но мы в комнате — спрашиваю канал целиком")
        }

        val proxy = layout.localProxy
        val trafficFlows = when {
            proxy == null -> null
            // Туннель погашен (мы дома или только что оттуда ушли) — локального входа
            // просто нет, спрашивать некого. Следующий заход спросит уже по-честному.
            !host.tunnelLive() -> null
            else -> probeThroughMain(host, proxy)
        }
        // Честная проба выше отвечает только на «идёт ли трафик». Троттлинг она не видит:
        // её ответ весит двести байт и проскакивает сквозь задушенную полосу целым.
        // Поэтому у живого канала отдельно спрашиваем, сколько он тянет ([SpeedProbe]).
        val squeeze = if (trafficFlows == true) SpeedProbe.measure(proxy, "основной канал") else null
        val squeezed = squeeze?.let(SpeedProbe::squeezed) ?: false
        if (squeezed) Log.w(TAG, "основной канал задушен ($squeeze) — держаться за него незачем")
        return noteMain(mainVerdict(portOpen, trafficFlows, squeezed), portOpen, squeeze.takeIf { squeezed })
    }

    /**
     * Теневая запись про основной канал. Вердикт [works] уже вынесен и не меняется —
     * здесь только записывается, откуда он взялся.
     *
     * Разница между «мерили» и «догадались» тут не косметическая: честная проба видит
     * весь путь, а открытый порт — одно рукопожатие. Человеку показываем то, что есть,
     * не выдавая догадку за замер.
     */
    private fun noteMain(works: Boolean, portOpen: Boolean?, squeeze: SpeedProbe.Speed? = null): Boolean {
        when (val probe = lastMainProbe) {
            // Задушенный канал в реестре не «живой»: соединение есть, а пользоваться им
            // нельзя, и человеку на главном экране это должно быть видно так же, как отказ.
            is ProxyProbe.Result.Live -> if (squeeze != null) {
                PathRegistry.dead(PathId.MAIN, "канал задушен: $squeeze", squeezed = true)
            } else {
                PathRegistry.alive(PathId.MAIN, probe.latencyMs)
            }
            is ProxyProbe.Result.Dead -> PathRegistry.dead(PathId.MAIN, probe.reason)
            null -> when (portOpen) {
                false -> PathRegistry.dead(PathId.MAIN, "адрес узла не отвечает", Evidence.Hint)
                true -> PathRegistry.alive(PathId.MAIN, evidence = Evidence.Hint)
                // Раскладку не поняли: отказ не выдумываем, но и замером это не назовёшь.
                null -> PathRegistry.alive(
                    PathId.MAIN,
                    evidence = Evidence.Never,
                    reason = "про канал не известно ничего",
                )
            }
        }
        return works
    }

    /**
     * Итог по двум пробам. Вынесено отдельно и без обращений к Android, чтобы главное
     * утверждение — «порт отвечает, а трафика нет, значит канал мёртв» — можно было
     * проверить, а не пересказать.
     *
     * @param portOpen хоть один адрес узла принял соединение; `null` — адресов в конфиге нет.
     * @param trafficFlows через канал прошёл запрос и вернулся ответ; `null` — честной пробы
     *   не было (нет локального входа в конфиге или туннель сейчас погашен).
     */
    internal fun mainVerdict(
        portOpen: Boolean?,
        trafficFlows: Boolean?,
        squeezed: Boolean = false,
    ): Boolean = when {
        // Трафик идёт, но полоса задушена: формально путь жив, а человеку он бесполезен.
        // Ровно этот случай держал хозяина на входе 443 неделями — проба на двести байт
        // проскакивала сквозь троттлинг и подтверждала «канал в порядке».
        trafficFlows == true && squeezed -> false
        // Честная проба главнее всего: она видит весь путь, а не только рукопожатие.
        // Порядок тут важен. Раньше первым стояло «порт молчит — канал мёртв», и вердикт
        // не менялся, даже если через канал в этот же миг прошёл запрос и вернулся ответ.
        // Обычно противоречия нет — но именно в комнате мы теперь спрашиваем канал целиком
        // при молчащем адресе узла, и старый порядок обесценил бы этот вопрос.
        trafficFlows != null -> trafficFlows
        // Честной пробы не было — остаётся верить рукопожатию.
        portOpen == false -> false
        // Честной пробы нет — остаётся верить порту, как до правки.
        portOpen != null -> portOpen
        // Про канал не известно ничего. Отказ не выдумываем.
        else -> true
    }

    /**
     * Мерить ли основной путь, несмотря на подсказку «белый список».
     *
     * Обычно подсказке верим на слово: под белым списком адрес узла недостижим, и проба
     * купила бы этот же ответ за полминуты. Но пока мы сидим в комнате, цена вопроса
     * другая: подсказка живёт [HINT_TTL_MILLIS], и всё это окно основной путь не меряется
     * ни полным заходом, ни приглядкой — то есть человек досиживает медленный путь при
     * канале, который мог ожить в первую же минуту.
     *
     * Второе условие обязательно: мерить можно только тем, что не рвёт живые соединения.
     * Есть закреплённый вход основного пути ([AutoModeExits.Layout.mainPinned]) — проба
     * идёт мимо селектора и не стоит никому ничего. Нет — единственный способ померить
     * это переставить селектор туда и обратно, а такую пробу убрали 12.08.2026 (у боевого
     * селектора `interrupt_exist_connections: true`, и каждая проба рвала всё живое дважды).
     * Возвращать её нельзя, поэтому без закреплённого входа остаёмся на подсказке.
     */
    internal fun measuresMainDespiteHint(inRoom: Boolean, mainPinned: Boolean): Boolean =
        inRoom && mainPinned

    /**
     * Честная проба именно основного канала.
     *
     * Локальный вход sing-box уводит запрос в тот выход, который выбран сейчас. Пока мы
     * стоим на основном канале, это ровно то, что нужно. Пока стоим в комнате — надо
     * на время пробы переставить селектор на основной и вернуть обратно, если он не ожил.
     *
     * Но переставлять надо только тогда, когда иначе путь не измерить. У основного канала
     * есть свой закреплённый вход ([AutoModeExits.Layout.mainPinned]), и через него проба
     * идёт мимо селектора. Раньше перестановка делалась всегда: у боевого селектора стоит
     * `interrupt_exist_connections: true`, поэтому каждая проба из комнаты рвала ВСЕ живые
     * соединения, и дважды — туда и обратно. При ритме заходов в комнате раз в три минуты
     * это давало два разрыва всего живого каждые три минуты. Комментарий на этом месте
     * раньше утверждал обратное («существующие соединения селектор не рвёт») и потому
     * дефект жил.
     */
    private fun probeThroughMain(host: Host, proxy: AutoModeExits.Endpoint): Boolean {
        val group = layout.chooser
        val main = layout.main

        // Куда вернуть выбор, если основной так и не ожил. null — возвращать некуда:
        // либо переключать нечем, либо мы и так стоим на основном.
        var restore: String? = null
        if (group != null && main != null && selected != main && !layout.mainPinned) {
            // Пересборка ядра (её делает подъём комнаты) стирает [selected], и тогда
            // возвращать было некуда: селектор оставался на мёртвом основном канале,
            // хотя стояли мы в комнате. Знать, где стоим, можно и без [selected] —
            // это выход текущей обстановки.
            restore = (selected ?: exitFor(gate.current))?.takeIf { it != main }
            runCatching { host.selectExit(group, main) }
                .onSuccess {
                    selected = main
                    Log.i(TAG, "на время пробы переставил выход на «$main»")
                }
                .onFailure { Log.w(TAG, "выход на «$main» переставить не вышло: ${it.message}") }
        }

        val result = ProxyProbe.through(proxy, PROBE_HOST, PROBE_PORT, PROBE_TIMEOUT_MILLIS)
        ProxyProbe.log("основной канал", result)
        // Итог пробы забирает [noteMain]: задержку и причину знает только она, а вердикт
        // выносится выше и от записи не зависит.
        lastMainProbe = result
        val alive = result is ProxyProbe.Result.Live
        // Через канал прошёл запрос и вернулся ответ — под белым списком такого не бывает
        // вовсе. Подсказку об обратном опровергаем делом, а не ждём её старости.
        if (alive) nodeAnswered("через основной канал прошёл запрос")

        if (!alive && restore != null && group != null) {
            runCatching { host.selectExit(group, restore) }
                .onSuccess {
                    selected = restore
                    Log.i(TAG, "основной канал не ожил — выход вернул на «$restore»")
                }
                .onFailure { Log.w(TAG, "выход вернуть на «$restore» не вышло: ${it.message}") }
        }
        return alive
    }

    /**
     * Примет ли адрес соединение.
     *
     * Сокет уводится мимо нашего же tun ([ProbeSocket]): одна привязка к сети от правила
     * per-uid не спасает, и при поднятом туннеле «узел отвечает» означало только то, что
     * узел отвечает через наш собственный туннель.
     */
    private fun connects(
        network: Network,
        endpoint: AutoModeExits.Endpoint,
        timeoutMillis: Int,
    ): Boolean = runCatching {
        val address = network.getAllByName(endpoint.host).firstOrNull() ?: return false
        ProbeSocket.open { network.bindSocket(it) }.use { socket ->
            socket.connect(InetSocketAddress(address, endpoint.port), timeoutMillis)
            true
        }
    }.getOrElse { false }

    /**
     * Примет ли соединение **хоть один** из адресов узла.
     *
     * Спрашиваем разом, а не по очереди. Молчащий узел — обычное дело под белым списком,
     * и при двух адресах в конфиге очередь стоила заходу два полных таймаута подряд:
     * восемь секунд, все из которых экран честно писал «Связи нет». Пакетов при этом
     * столько же, сколько было, — по одному SYN на адрес, один раз за заход; они просто
     * больше не ждут друг друга. Первый согласившийся адрес закрывает вопрос, остальные
     * снимаются.
     */
    private fun anyConnects(
        network: Network,
        endpoints: List<AutoModeExits.Endpoint>,
        timeoutMillis: Int,
    ): Boolean {
        if (endpoints.isEmpty()) return false
        if (endpoints.size == 1) return connects(network, endpoints[0], timeoutMillis)
        val pool = Executors.newFixedThreadPool(endpoints.size)
        try {
            val answers = ExecutorCompletionService<Boolean>(pool)
            endpoints.forEach { endpoint ->
                answers.submit { connects(network, endpoint, timeoutMillis) }
            }
            val deadline = SystemClock.elapsedRealtime() + timeoutMillis + CONNECT_SLACK_MILLIS
            repeat(endpoints.size) {
                val left = deadline - SystemClock.elapsedRealtime()
                if (left <= 0) return false
                val done = runCatching { answers.poll(left, TimeUnit.MILLISECONDS) }.getOrNull() ?: return false
                if (runCatching { done.get() }.getOrDefault(false)) return true
            }
            return false
        } finally {
            pool.shutdownNow()
        }
    }

    /**
     * Приглядка из комнаты: одно рукопожатие до узла основного канала.
     *
     * Стоя в комнате, о снятии ограничения мы узнавали только по ритму полных заходов —
     * то есть в лучшем случае через три минуты.
     * Здесь спрашивается ровно то, что под белым списком отвечать не может: примет ли
     * адрес узла соединение. Ответил — обстановка сменилась, и дальше разбирается
     * полный заход, разбуженный сейчас же.
     *
     * Адрес берётся один и по очереди, TLS нет, соединения не параллелятся — цена вопроса
     * один SYN, а под запретом ещё и молчание до [ROOM_PEEK_TIMEOUT_MILLIS].
     *
     * @return true — узел ответил, полный заход нужен немедленно.
     */
    private fun peekMain(): Boolean {
        if (!Settings.autoModeEnabled) return false
        // Узел уже отвечает — рукопожатие не узнает ничего нового. Спрашиваем путь целиком.
        if (!peekWanted) return peekThroughMain()
        val endpoints = layout.mainEndpoints
        if (endpoints.isEmpty()) return false
        val network = physicalNetwork() ?: return false
        val endpoint = endpoints[(peekAt++ % endpoints.size).coerceAtLeast(0)]
        if (!connects(network, endpoint, ROOM_PEEK_TIMEOUT_MILLIS)) {
            // Молчание — обычный исход под запретом, и вслух о нём говорить незачем, кроме
            // как для разбора: без этой строки не видно, ходила приглядка вообще или нет.
            Log.i(TAG, "приглядка из комнаты: узел ${endpoint.host}:${endpoint.port} молчит")
            return false
        }
        Log.i(TAG, "приглядка из комнаты: узел основного канала ответил — проверяю канал целиком")
        nodeAnswered("узел ответил на приглядку из комнаты")
        // Серией перепроверок пользуемся той же, что и после смены сети: обстановка
        // изменилась ровно так же доказанно, а подтверждений задвижка при этом всё равно
        // требует — переключение остаётся защищённым от одиночного везения.
        burst.restart()
        return true
    }

    /**
     * Приглядка из комнаты для случая, когда узел отвечает: честная проба всего пути.
     *
     * Рукопожатие тут бесполезно — оно и так проходит. Душат не установку соединения,
     * а транспорт: узел принимает SYN, а запрос через канал не возвращается. Различить
     * «всё ещё душат» и «отпустило» может только запрос, прошедший путь целиком, — им
     * и спрашиваем. Раньше на этом месте приглядка молча выключалась, и пока комната
     * отвечала, основной путь между трёхминутными заходами не проверялся ничем.
     *
     * Три условия, и все три про то, чтобы проба ничего не сломала:
     *  - **закреплённый вход** ([AutoModeExits.Layout.mainPinned]) — проба идёт мимо
     *    селектора. Без него мерить пришлось бы перестановкой селектора, а она рвёт все
     *    живые соединения (убрано 12.08.2026, см. [probeThroughMain]) — тогда лучше никак;
     *  - **живой туннель** — иначе локального входа просто нет и стучаться некуда;
     *  - **свой ритм** ([ROOM_HONEST_PEEK_MILLIS]) — проба дороже рукопожатия, и гонять
     *    её на каждом куске паузы (20-40 с) незачем.
     *
     * @return true — путь ответил, полный заход нужен немедленно.
     */
    private fun peekThroughMain(): Boolean {
        val host = this.host ?: return false
        if (!layout.mainPinned) return false
        val proxy = layout.localProxy ?: return false
        if (!runCatching { host.tunnelLive() }.getOrDefault(false)) return false
        val now = SystemClock.elapsedRealtime()
        if (!honestPeekDue(honestPeekAt.takeIf { it != 0L }?.let { now - it })) return false
        honestPeekAt = now

        lastMainProbe = null
        val alive = probeThroughMain(host, proxy)
        // Замер настоящий и ровно про основной путь — в реестр он ложится так же, как из
        // полного захода: иначе экран все три минуты держал бы запись прошлого захода.
        noteMain(alive, portOpen = null)
        refreshLink()
        if (!alive) return false
        Log.i(TAG, "приглядка из комнаты: основной путь ответил на честную пробу — проверяю обстановку целиком")
        // Серией перепроверок пользуемся той же, что и после смены сети: обстановка
        // изменилась так же доказанно, а подтверждений задвижка всё равно требует —
        // переключение остаётся защищённым от одиночного везения.
        burst.restart()
        return true
    }

    /**
     * Пора ли честной пробе из комнаты. Вынесено без обращений к Android: ритм — это
     * утверждение о поведении, и проверяться оно должно тестом.
     *
     * @param sinceMillis сколько прошло с прошлой пробы; `null` — её не было ни разу.
     */
    internal fun honestPeekDue(sinceMillis: Long?, everyMillis: Long = ROOM_HONEST_PEEK_MILLIS): Boolean =
        sinceMillis == null || sinceMillis >= everyMillis

    /**
     * Ожидание внутри комнаты: тот же ритм полных заходов, но с приглядкой между ними.
     *
     * Пауза режется на куски случайной длины ([ROOM_PEEK_MIN_MILLIS]..[ROOM_PEEK_MAX_MILLIS]),
     * и на границе каждого идёт приглядка: рукопожатие до узла, пока он молчит, и честная
     * проба всего пути ([peekThroughMain], своим ритмом), когда он уже отвечает. Ровного
     * интервала не получается ни у проб, ни у заходов — метронома, который видно снаружи,
     * тут нет.
     *
     * Разбудили раньше (сменилась сеть, пересобралось ядро) — выходим сразу: заход и так
     * вот-вот будет, и тратить на приглядку лишнее рукопожатие незачем.
     */
    private fun waitInRoom(total: Long) {
        var left = total
        while (active && left > 0) {
            val slice = minOf(left, Random.nextLong(ROOM_PEEK_MIN_MILLIS, ROOM_PEEK_MAX_MILLIS + 1))
            val before = SystemClock.elapsedRealtime()
            waitNext(slice)
            val spent = SystemClock.elapsedRealtime() - before
            left -= spent
            if (!active) return
            // Проснулись до срока — это не наш таймер, а событие.
            if (spent < slice - WAKE_SLACK_MILLIS) return
            if (left <= 0) return
            if (peekMain()) return
        }
    }

    /**
     * Приглядка дома: один прямой запрос наружу между полными заходами.
     *
     * Дома мы слепы по устройству: туннель погашен, ядра нет, своих исходящих нет — и
     * ограничению, наступившему на той же сети, не через что о себе заявить. На стенде
     * 10.08.2026 это стоило 2 минут 44 секунд «дома» при мёртвой связи, причём разбудило
     * автомат в итоге не наблюдение, а система: она сама сняла с сети признак VALIDATED,
     * когда её собственная проверка интернета не прошла.
     *
     * Спрашиваем ровно то, что в такой сети умирает первым, — проходит ли наружу запрос.
     * Резолвер для этого не годится, хотя он и дешевле: под ограничением он продолжает
     * отвечать подменными адресами как ни в чём не бывало, и признак дома остаётся верным.
     * Почему так и сколько это стоит — [HomeWatch].
     *
     * Удачная проба не пропадает: это тот же самый замер пути «дома», что делает полный
     * заход ([homeCarriesTraffic]), и в реестр он ложится так же.
     *
     * @return true — наружу перестало проходить, полный заход нужен немедленно.
     */
    private fun peekHome(): Boolean {
        if (!Settings.autoModeEnabled) return false
        // Сети не стало — заход разберётся сам, и позовёт его событие от системы.
        val network = physicalNetwork() ?: return true
        val measurement = HonestProbe.measureDirect(network, "дома, приглядка")
        if (!HomeWatch.wake(measurement.live)) {
            // Замер настоящий и ровно про путь «дома» — терять его незачем: без этой
            // записи экран все пять минут показывал бы возраст последнего полного захода.
            PathRegistry.alive(PathId.HOME, measurement.latencyMs)
            refreshLink()
            return false
        }
        Log.i(TAG, "приглядка дома: наружу не проходит ($measurement) — проверяю обстановку целиком")
        // Серией перепроверок пользуемся той же, что и после смены сети: обстановка
        // изменилась так же доказанно, а подтверждений задвижка при этом всё равно
        // требует — переключение остаётся защищённым от одиночного невезения.
        //
        // Но только если замер СОСТОЯЛСЯ. Не состоялся он ровно по одной причине — имя
        // цели не резолвится, то есть те же молчащие резолверы. Доказанного изменения
        // обстановки тут нет, а серия выдаёт задвижке поблажку в подтверждениях: заход
        // дома был бы принят со второго раза вместо третьего. Полный заход всё равно
        // зовём (он разберётся сам), но ускорять решение молчанием не станем.
        if (measurement.measured) burst.restart()
        return true
    }

    /**
     * Ожидание дома: тот же ритм полных заходов, но с дешёвой пробой между ними.
     *
     * Устроено так же, как ожидание в комнате: пауза режется на куски случайной длины
     * ([HomeWatch.slice]), и на границе каждого идёт одна проба. Разбудили раньше
     * (сменилась сеть, пересобралось ядро) — выходим сразу: заход и так вот-вот будет,
     * и тратить на пробу лишний запрос незачем.
     */
    private fun waitAtHome(total: Long) {
        var left = total
        while (active && left > 0) {
            val slice = HomeWatch.slice(
                left,
                Random.nextLong(HomeWatch.MIN_MILLIS, HomeWatch.MAX_MILLIS + 1),
            )
            val before = SystemClock.elapsedRealtime()
            waitNext(slice)
            val spent = SystemClock.elapsedRealtime() - before
            left -= spent
            if (!active) return
            // Проснулись до срока — это не наш таймер, а событие.
            if (spent < slice - WAKE_SLACK_MILLIS) return
            if (left <= 0) return
            if (peekHome()) return
        }
    }

    /**
     * Идёт ли через комнату трафик. Своей пробы не заводим: её владелец один —
     * [OlcRtcWatchdog]. Тумблер тут не спрашиваем: живое ядро живо независимо от него,
     * а сам тумблер — аварийный выключатель и работает там, где комнату поднимают.
     */
    private fun roomAlive(): Boolean = OlcRtcCore.state is OlcRtcCore.State.Ready &&
        OlcRtcCore.health is OlcRtcCore.Health.Live

    /** Поднято ли ядро комнаты. Ответ самого ядра, без ожидания вердикта присмотра. */
    private fun roomUp(): Boolean = OlcRtcCore.state is OlcRtcCore.State.Ready

    /**
     * Комната ещё не сказала своего слова: либо поднимается, либо поднялась, но присмотр
     * её пока не мерил. Гасить в этот момент нельзя — это и есть убийство собственной пробы.
     */
    private fun roomSettling(): Boolean = OlcRtcCore.state is OlcRtcCore.State.Starting ||
        (OlcRtcCore.state is OlcRtcCore.State.Ready && OlcRtcCore.health is OlcRtcCore.Health.Unknown)

    private fun name(situation: Situation): String = when (situation) {
        Situation.Home -> "дома"
        Situation.Main -> "основной канал"
        Situation.Room -> "комната"
        Situation.Searching -> "ничего не поднимается"
        Situation.NoNetwork -> "сети нет"
        Situation.Unknown -> "неизвестно"
    }
