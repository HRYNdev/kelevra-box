    /**
     * Включает автомат. Звать после того, как сервис поднялся.
     *
     * @param initial обстановка, которую уже определили на старте (чтобы не поднимать
     *   туннель дома и тут же его гасить).
     */
    fun start(host: Host, initial: Situation = Situation.Unknown) {
        synchronized(lock) {
            stopLocked()
            this.host = host
            // Персистентный выбор человека подтягиваем только теперь: см. комментарий у поля.
            // Settings и manualExit всегда синхронны (каждый мутатор пишет в оба разом), так
            // что повторное чтение на втором start() в том же процессе ничего не меняет.
            manualExit = Settings.manualExitName.takeIf { it.isNotBlank() }
            layout = host.profileConfig()?.let { AutoModeExits.parse(it, OlcRtcParams.socksPort) }
                ?: AutoModeExits.Layout.EMPTY
            gate.reset(initial)
            // На чьей сети стоит начальная обстановка, мы ещё не знаем — узнаем первым
            // же заходом. До того держать вердикт на молчании не на чем ([holdsVerdict]).
            situationNetwork = null
            silentHoldAt = 0L
            observationSilent = false
            searchingRounds = 0
            selected = null
            // Сервис только что поднялся — обстановка по определению «только что изменилась»,
            // и первое наблюдение можно принять сразу, не выжидая три захода.
            networkChanged = true
            lastNetwork = DefaultNetworkMonitor.defaultNetwork
            lastValidated = lastNetwork?.let(::validated) ?: false
            burst.cancel()
            settled = false
            idle = false
            pendingSwitch = false
            roomTriedAt = 0L
            roomTrialPause = ROOM_TRIAL_PAUSE_MILLIS
            mainFailures = 0
            nodeAnsweredAt = 0L
            peekAt = 0
            peekWanted = false
            honestPeekAt = 0L
            forgetHomeSign()
            // Прошлая сессия про эти пути больше ничего не знает: сеть под нами могла
            // смениться, пока сервиса не было.
            PathRegistry.reset()
            // Сюда приходит и ручное переподключение: человек дёрнул выключатель именно
            // потому, что вокруг что-то не так, как мы думаем. Его вмешательство —
            // такое же событие «обстановка сменилась», как и смена сети.
            NetworkModeDetector.forget("человек переподключил сервис")
            PathRegistry.bindExits(main = layout.main, room = layout.room)
            link = Link.Unknown
            holdNetwork = physicalNetwork()
            holdKey = holdNetwork?.let { networkKey(it) }
            // Выбор руками переживает перезапуск сервиса (он в настройках), а значит и срок
            // его жизни надо с чего-то начинать: иначе после каждого перезапуска выбор был
            // бы «только что сделан» и не истекал бы никогда.
            holdAt = if (manualExit != null) SystemClock.elapsedRealtime() else 0L
            publish(Settings.autoModeEnabled, initial)
            active = true
            thread = Thread(::loop, "automode").apply {
                isDaemon = true
                start()
            }
            Log.i(
                TAG,
                "автомат включён (${if (Settings.autoModeEnabled) "сам" else "выключен человеком"}): " +
                    "выбор ${layout.chooser ?: "нет"}, основной ${layout.main ?: "нет"}, " +
                    "комната ${layout.room ?: "нет"}, адресов ${layout.mainEndpoints.size}",
            )
        }
    }

    fun stop() {
        synchronized(lock) { stopLocked() }
    }

    private fun stopLocked() {
        if (!active && thread == null) return
        active = false
        val t = thread
        thread = null
        lock.notifyAll()
        t?.interrupt()
        t?.join(1_000)
        host = null
        PathRegistry.reset()
        link = Link.Unknown
        publish(Settings.autoModeEnabled, Situation.Unknown)
        Log.i(TAG, "автомат выключен")
    }

    /**
     * Системе есть что сказать про сеть по умолчанию. Колбэк приходит из системного
     * потока — только будим свой.
     *
     * Приходит он на три разных события: появилась новая сеть, основной стала другая,
     * система подтвердила на ней интернет. Плюс на всякую мелочь вроде уровня сигнала —
     * а вот на неё будить автомат нельзя: полный круг проб стоит батареи, и хуже того,
     * каждое такое «событие» принималось бы без подтверждений, то есть защита от
     * дёрганья работала бы только на бумаге. Поэтому реагируем на смену самой сети
     * и на смену её проверенности, а не на каждый чих.
     *
     * @param network сеть, которую система считает основной; null — её не стало.
     */
    fun onNetworkChanged(network: Network?) {
        if (!active) return
        val nowValidated = network?.let(::validated) ?: false
        val nowKey = network?.let(::networkKey)
        if (network == lastNetwork && nowValidated == lastValidated && nowKey == lastNetworkKey) {
            // Сеть та же и отпечаток тот же — с точки зрения Android не произошло ничего.
            // Ровно так выглядит роуминг между репитером и роутером: один NetworkAgent
            // переживает несколько циклов ухода/возврата, и «сеть сменилась» не пишется
            // никогда. Но шлюз, резолверы и уровень сигнала при этом меняются — снимок
            // связи это покажет, а он пишется, только когда изменился.
            noteLink(network, "система сообщила о сети")
            return
        }
        // Тот же вайфай, но у него появились (или сменились) резолверы — это не «чих»,
        // а именно тот момент, когда сеть стало можно спрашивать про дом.
        val onlyResolvers = network != null && network == lastNetwork && nowValidated == lastValidated
        lastNetwork = network
        lastValidated = nowValidated
        lastNetworkKey = nowKey
        networkChanged = true
        if (onlyResolvers) {
            Log.i(TAG, "сеть та же, но резолверы сменились: ${describe(network)} — перепроверяю")
        } else {
            Log.i(TAG, "сеть сменилась: ${describe(network)}")
        }
        noteLink(network, "смена сети")
        // Подсказка про режим сети привязана к объекту сети, и другую сеть она уже не
        // касается сама. Но сюда мы приходим и когда сеть та же, а система только что
        // подтвердила на ней интернет, — а это ровно то, что происходит, когда с соты
        // снимают ограничение. Держаться в такой момент за прошлый вердикт значит
        // проспать снятие до его старости.
        NetworkModeDetector.forget("сеть сменилась или переподтвердилась")
        nodeAnsweredAt = 0L
        // Ручной выбор — это «стой здесь», а не «выключи автомат навсегда». Он держится,
        // пока мы в той же сети: под неё человек и выбирал. Сеть другая — обстановка
        // другая, и держаться за прошлый выбор значит увезти человека в мёртвый выход.
        // Сравниваем именно физические сети: наш собственный туннель тоже приходит сюда
        // сменой сети по умолчанию, и по ней выбор отпускался бы через секунду после того,
        // как его сделали.
        //
        // Спрашиваем ПАМЯТЬ (`_state.value.auto`), а не `Settings` — и это не оптимизация.
        // Сюда мы приходим прямо из системного колбэка, на ConnectivityThread
        // ([DefaultNetworkListener] крутит актор на Unconfined и шлёт через runBlocking).
        // `Settings` — это Room, то есть синхронный поход на диск: до первой разблокировки
        // телефона CE-хранилища ещё нет, и вместо ответа прилетает исключение, которое
        // убивает весь процесс вместе с актором сетевых событий. Поймано в бою 15.08.2026.
        // `_state.value.auto` — тот же флаг, его держат в согласии [setEnabled],
        // [chooseManually], [releaseManualHold] и старт автомата.
        if (!_state.value.auto) {
            val now = physicalNetwork()
            val nowKey = now?.let { networkKey(it) }
            // Сеть считаем сменившейся по отпечатку, а не по объекту: см. [holdKey].
            if (now != null && nowKey != null && holdKey != null && nowKey != holdKey) {
                releaseManualHold(now)
            }
        }
        synchronized(lock) { lock.notifyAll() }
    }

    /**
     * Ядро sing-box пересобрали не в заходе автомата, а где-то сбоку — и ждать нашего
     * таймера незачем.
     *
     * Зовёт [io.nekohasekai.sfa.bg.BoxService], когда в стороне досчитал подъём комнаты.
     * Дел тут два, и оба про скорость. Первое: пересборка сбрасывает селектор на первый
     * выход конфига, значит наша память о выбранном протухла. Второе и главное: комната
     * встаёт до полутора минут, и если после этого досиживать очередной шаг ритма, весь
     * выигрыш от асинхронного подъёма уходит в ожидание. Будим заход прямо сейчас — он
     * увидит поднятую комнату той же секундой.
     */
    fun onCoreRebuilt(reason: String) {
        if (!active) return
        Log.i(TAG, "ядро пересобрано ($reason) — выбор сбрасываю, иду на заход не дожидаясь ритма")
        selected = null
        // И перечитываем раскладку. Проверочные входы ([ProbeInboundPatch]) занимают
        // СВОБОДНЫЕ порты, а свободные они каждый раз разные: после пересборки старые
        // номера ведут в никуда. Раньше раскладка читалась только на старте автомата,
        // и проба честно стучалась в порт из прошлой жизни ядра — на телефоне это
        // выглядело как «Не отвечает» при живом канале (11.08.2026: путь «Нидерланды»
        // отвечал за 336 мс через свежий вход, а «основной канал» молчал на старом).
        refreshLayout(reason)
        synchronized(lock) { lock.notifyAll() }
    }

    /** Перечитывает раскладку выходов и входов из конфига, который сейчас в ядре. */
    private fun refreshLayout(reason: String) {
        val content = runCatching { host?.profileConfig() }.getOrNull() ?: return
        val fresh = runCatching { AutoModeExits.parse(content, OlcRtcParams.socksPort) }.getOrNull() ?: return
        if (fresh.localProxy == layout.localProxy && fresh.mainEndpoints == layout.mainEndpoints) return
        layout = fresh
        PathRegistry.bindExits(main = fresh.main, room = fresh.room)
        Log.i(
            TAG,
            "раскладка перечитана ($reason): вход основного ${fresh.localProxy?.port ?: "нет"}, " +
                "адресов узла ${fresh.mainEndpoints.size}",
        )
    }

    /** Ручной выбор больше ничего не значит, автомат снова сам. */
    private fun releaseManualHold(network: Network?, why: String = "сеть сменилась") {
        Log.i(TAG, "$why — ручной выбор «${manualExit ?: "нет"}» отпущен, автомат снова сам")
        holdNetwork = network
        holdKey = network?.let { networkKey(it) }
        holdAt = 0L
        manualExit = null
        Settings.manualExitName = ""
        Settings.autoModeManualRoom = false
        Settings.autoModeEnabled = true
        idle = false
        selected = null
        gate.reset(Situation.Unknown)
        situationNetwork = null
        silentHoldAt = 0L
        mainFailures = 0
        PathRegistry.reset()
        link = Link.Unknown
        publish(true, Situation.Unknown)
    }

    /** Сколько живёт нынешний выбор руками; `null` — выбора нет. */
    private fun manualHoldAge(): Long? =
        holdAt.takeIf { it != 0L }?.let { SystemClock.elapsedRealtime() - it }

    /**
     * Пора ли отпускать выбор, сделанный руками.
     *
     * Вынесено отдельно и без обращений к Android: утверждение «выбор живёт не дольше
     * часа, но и не отпускается раньше» должно проверяться, а не пересказываться.
     *
     * @param ageMillis сколько выбор держится; `null` — выбора нет.
     */
    internal fun manualHoldExpired(ageMillis: Long?, ttlMillis: Long = MANUAL_HOLD_MILLIS): Boolean =
        ageMillis != null && ageMillis >= ttlMillis

    /** Человек включил или выключил автомат. */
    fun setEnabled(enabled: Boolean) {
        // «Авто режим сам включает VPN на вайфае» разбирается только тогда, когда в
        // журнале видно, был ли автомат вообще включён и кто его переключил.
        Log.i(TAG, "автомат ${if (enabled) "включён" else "выключен"} человеком")
        Settings.autoModeEnabled = enabled
        if (enabled) {
            manualExit = null
            Settings.manualExitName = ""
            Settings.autoModeManualRoom = false
            holdNetwork = null
            holdAt = 0L
            PathRegistry.reset()
            link = Link.Unknown
        }
        _state.value = _state.value.copy(auto = enabled, link = link)
        gate.reset(Situation.Unknown)
        situationNetwork = null
        silentHoldAt = 0L
        mainFailures = 0
        networkChanged = true
        synchronized(lock) { lock.notifyAll() }
    }

    /** Имя комнаты приходит с сервера, поэтому узнаём её по корню слова, как и экран. */
    private fun looksLikeRoom(tag: String): Boolean =
        tag.lowercase().let { it.contains("комнат") || it.contains("room") }

    /**
     * Человек выбрал выход руками. Автомат при этом отходит: иначе он через минуту
     * передумает, и выбор не удержится.
     *
     * Отходит **до смены сети**, а не навсегда. Выбор всегда сделан под то, что вокруг
     * прямо сейчас («здесь основной канал живой, хочу его»), и в другой сети он значит
     * ровно ничего — а раньше один случайный тык оставлял человека без автомата до тех
     * пор, пока он сам не вспомнит про пункт «Автоматически». Отпускает выбор
     * [onNetworkChanged], состояние «выбрано вручную» видно на главном экране.
     *
     * Комнату сюда тащим осознанно: ядро olcRTC поднимается не только по решению автомата,
     * но и когда человек выбрал комнату сам. Выбор запоминаем в настройках, потому что он
     * должен пережить перезапуск сервиса — иначе после перезагрузки телефона выбранная
     * комната оказалась бы выбранной, но не поднятой.
     */
    fun chooseManually(tag: String): Boolean {
        manualExit = tag
        Settings.manualExitName = tag
        // Экран сразу применяет выбор в ядре, поэтому запоминаем его и мы: иначе автомат
        // будет считать, что стоит на основном канале, и мерять пробой чужой выход.
        //
        // Но только когда ядро вообще есть. При выключенной сети команду отдавать некому,
        // и запись «уже выбрано» заставляла choose() промолчать после старта: ядро
        // оставалось на своём дефолте. Ровно так выбранная комната превращалась в
        // «Нидерланды, выбран вручную» (поймано в эмуляторе 07.08.2026).
        selected = if (host != null) tag else null
        // Комнату узнаём и по имени тоже. Раскладка приходит от работающего ядра, а выбор
        // делают чаще всего до включения сети: тогда layout.room пуст, сравнивать не с чем,
        // и выбранная комната записывалась как обычный выход. Ниже, в round(), выбор ещё
        // раз уточняется по раскладке, когда она появится.
        val room = layout.room?.let { tag == it } ?: looksLikeRoom(tag)
        Settings.autoModeManualRoom = room
        // Человек выбрал комнату — значит аварийный выключатель, если он был нажат,
        // он снимает этим же действием. Без этого выбор комнаты молча давал обычный
        // выход: круг писал «Комната», нога не видела участника вовсе (поймано в
        // эмуляторе 07.08.2026).
        if (room) Settings.olcrtcEnabled = true
        Settings.autoModeEnabled = false
        // Сеть, под которую сделан выбор. Сменится — автомат вернётся сам.
        holdNetwork = physicalNetwork()
        holdKey = holdNetwork?.let { networkKey(it) }
        // И время выбора: на соте смены сети можно не дождаться никогда ([MANUAL_HOLD_MILLIS]).
        holdAt = SystemClock.elapsedRealtime()
        // Прошлые замеры делались под выбор автомата: держать их и показывать как правду
        // про выход, который человек выбрал сам, значит врать.
        PathRegistry.reset()
        link = Link.Unknown
        _state.value = _state.value.copy(auto = false, situation = Situation.Unknown, link = link)
        gate.reset(Situation.Unknown)
        situationNetwork = null
        silentHoldAt = 0L
        mainFailures = 0
        idle = false
        Log.i(
            TAG,
            "выход выбран руками: «$tag» (комната: ${Settings.autoModeManualRoom}) — " +
                "держим до смены сети",
        )
        synchronized(lock) { lock.notifyAll() }
        // Применять ли выбор в ядре немедленно. Для обычного выхода — да. Для комнаты —
        // только если она уже стоит: её ядро поднимается в своём потоке и на живом
        // телефоне это заняло 103 секунды (замер 12.08.2026). Пока socks комнаты не
        // слушает, переставленный селектор отправляет туда весь проксируемый трафик, и он
        // получает мгновенный отказ `connection refused`, хотя круг уже пишет
        // «Подключено». Выбор применится сам, когда комната встанет: подъём заканчивается
        // пересборкой ядра и вызовом [onCoreRebuilt], а заход в ручном режиме возвращает
        // выбор человека каждым кругом.
        val roomChosen = Settings.autoModeManualRoom
        val roomUp = OlcRtcCore.state is OlcRtcCore.State.Ready && OlcRtcCore.isRunning()
        if (roomChosen && !roomUp) {
            Log.i(TAG, "комната ещё не стоит — выбор применю, когда поднимется")
            return false
        }
        return true
    }

    /**
     * Проба «мы дома» одним вызовом, без запуска автомата. Нужна на старте сервиса:
     * дома туннель не надо поднимать вообще, а не поднимать и через секунду гасить.
     *
     * Признаков тут два, и оба обязательны — те же, что в заходе автомата: подменные
     * адреса от домашнего резолвера И реально уходящий наружу трафик. Одного DNS мало:
     * в сети с белым списком подменные адреса приходят так же (резолвер-то домашний
     * никуда не делся, если стоим у себя за роутером), а наружу не проходит ничего, —
     * и сервис стартовал бы вообще без туннеля, показывая «Дома».
     */
    fun homeRightNow(): Boolean = homeRightNow0().also {
        // От этого ответа зависит, поднимется ли туннель при старте вообще. Раньше он
        // нигде не писался, и «сервис стартовал с туннелем» приходилось выводить из
        // того, чего в журнале НЕТ.
        Log.i(TAG, "старт: ${if (it) "дома — ядро не поднимаю" else "не дома — поднимаю ядро"}")
    }

    private fun homeRightNow0(): Boolean {
        if (!Settings.autoModeEnabled) return false
        val network = physicalNetwork() ?: return false
        // В соте дома не бывает, а этот вопрос задаётся до подъёма ядра — то есть человек
        // ждёт подключения ровно столько, сколько мы его задаём. Четыре запроса к
        // резолверу ради заранее известного ответа тут стоили до 2.5 секунд.
        if (!homeReachable(network)) return false
        if (homeBypass(network) != HomeSign.Sign.Yes) return false
        return homeCarriesTraffic(network) == true
    }

    private fun loop() {
        while (active) {
            val situation = runCatching { round() }.getOrElse {
                Log.w(TAG, "заход сорвался: ${it.message}")
                _state.value.situation
            }
            if (!active) return
            // Серия перепроверок после смены сети идёт вперёд обычного ритма и обрывается
            // сама, как только обстановка устоялась.
            val hurry = burst.next(settled)
            if (hurry != null) Log.i(TAG, "серия после смены сети: следующая проверка через ${hurry / 1000.0} с")
            val wait = when {
                // Автомат выключен человеком — но спать вечно нельзя. Реестр путей
                // остаётся с тем, что было записано до ручного выбора, и экран пишет
                // «не отвечает» на живом канале: поймано на телефоне 10.08.2026 —
                // выбрали Нидерланды после комнаты, сайт открывается, а круг врёт.
                // Раз в минуту перемеряем выбранный путь: решать он ничего не будет,
                // но человеку показывается правда, а не старая запись.
                idle -> ROUND_MANUAL_MILLIS
                hurry != null -> hurry
                // Идёт набор подтверждений — досматриваем быстро, а не через пять минут.
                pendingSwitch -> ROUND_SEARCHING_MILLIS
                else -> delayFor(situation)
            }
            // Полный ритм комнаты и дома досиживаем не вслепую: между заходами идёт одна
            // дешёвая проба. Спешка (серия, набор подтверждений) в этом не нуждается —
            // там заход и так близко.
            when {
                wait == ROUND_ROOM_MILLIS && situation == Situation.Room -> waitInRoom(wait)
                // Дома проба ловит то, о чём иначе некому сказать: ограничение, наступившее
                // без смены сети. Ядра в этот момент нет, исходящих нет, ломаться нечему.
                wait == ROUND_HOME_MILLIS && situation == Situation.Home -> waitAtHome(wait)
                else -> waitNext(wait)
            }
        }
    }

    /** @return обстановка, на которой стоим после этого захода. */
    private fun round(): Situation {
        val host = this.host ?: return Situation.Unknown

        // Выбор руками отпускает [onNetworkChanged] по смене сети — но событие это на соте
        // не приходит вовсе, и человек оставался в выбранном выходе (чаще всего в комнате,
        // выбранной на время аварии) до тех пор, пока сам о нём не вспомнит. Срок жизни
        // выбора закрывает ровно эту дыру и только её: смена сети по-прежнему отпускает
        // выбор мгновенно, не дожидаясь часа.
        if (!Settings.autoModeEnabled && manualHoldExpired(manualHoldAge())) {
            // Обстановку после возврата смотрим как после смены сети: то, что мы про неё
            // знали, снималось под ручной выбор и уже ничего не значит.
            networkChanged = true
            releaseManualHold(physicalNetwork(), "выбор руками держится больше ${MANUAL_HOLD_MILLIS / 60_000} мин")
        }

        if (!Settings.autoModeEnabled) {
            // Человек выбирает выход сам. Обязанностей у нас тут две: вернуть туннель,
            // если сами же его погасили (иначе выбор руками упрётся в выключенное ядро),
            // и привести комнату в то состояние, которое следует из его выбора.
            if (host.resumeTunnel("автомат выключен человеком")) selected = null
            // Выбрать выход можно раньше, чем автомат прочитает конфиг: список выходов
            // экран строит сам, а раскладка появляется только к первому заходу. Тогда
            // [chooseManually] не с чем было сравнить имя и записал «не комната».
            // Сверяем ещё раз, как только раскладка есть, иначе выбранная комната
            // молча оставалась бы непóднятой.
            manualExit?.let { tag ->
                val room = layout.room
                if (room != null && Settings.autoModeManualRoom != (tag == room)) {
                    Settings.autoModeManualRoom = tag == room
                    Log.i(TAG, "выбор «$tag» уточнён по раскладке: комната = ${Settings.autoModeManualRoom}")
                }
            }
            val wantRoom = Settings.autoModeManualRoom
            val ack = runCatching {
                host.setRoomWanted(wantRoom, if (wantRoom) "комнату выбрал человек" else "человек выбрал обычный выход")
            }.getOrElse {
                Log.w(TAG, "комнату переключить не вышло: ${it.message}")
                RoomAck.Failed
            }
            if (ack.changed) {
                // Пересборка ядра сбрасывает выбор в селекторе на первый пункт конфига —
                // возвращаем то, что выбрал человек.
                selected = null
                // Гашение комнаты тоже пересобирает ядро — тем же движением, что и на
                // старте сервиса, входы для пробы получают новые свободные порты
                // ([ProbeInboundPatch]). Раскладку раньше здесь не перечитывали: только
                // подъём комнаты и возврат из дома звали [onCoreRebuilt]. Экран после
                // возврата из комнаты мерил основной канал по номеру входа из прошлой
                // жизни ядра — вход никто не слушал, и живой канал висел «Не отвечает»
                // до следующего повода перечитать раскладку (поймано 13.08.2026).
                refreshLayout("комната переключена вручную (комната: $wantRoom)")
            }
            // Выбор возвращаем каждым заходом, а не только когда трогали комнату. На старте
            // сервиса комнату поднимает уже BoxService, setRoomWanted отвечает «ничего не
            // менялось», и выбор человека не применялся вовсе: ядро оставалось на первом
            // выходе конфига. Ровно так выбранная комната работала как «Нидерланды»
            // (поймано в эмуляторе 07.08.2026). Лишних команд нет: choose молчит, когда
            // выбранное уже стоит.
            manualExit?.let { choose(host, it) }
            // Про комнату её ядро говорит и без нас: без этой записи выбранная руками
            // комната выглядела бы «непроверенной» всё время выбора.
            noteRoom()
            // А вот обычный выход мерить некому, кроме нас. Без этого реестр держит то,
            // что записали до ручного выбора, и круг пишет «не отвечает» на живом канале.
            if (!wantRoom) {
                physicalNetwork()?.let { net ->
                    runCatching { mainWorks(net, host) }
                        .onFailure { Log.w(TAG, "замер выбранного выхода не удался: ${it.message}") }
                }
            }
            idle = true
            burst.cancel()
            settled = true
            publish(auto = false, situation = Situation.Unknown)
            return Situation.Unknown
        }
        idle = false

        val trustOnce = networkChanged
        if (trustOnce) {
            networkChanged = false
            searchingRounds = 0
            burst.restart()
            Log.i(TAG, "сеть сменилась — перепроверяю обстановку")
        }

        val was = gate.current
        val observed = observe(host)

        // Резолверы промолчали, сеть та же, и стоим мы на рабочем выходе — вердикт «не
        // знаю». Задвижке такое наблюдение даже не показываем: набор подтверждений
        // означал бы, что молчание всё-таки считается доводом, просто медленнее.
        if (holdsVerdict(
                silent = observationSilent,
                observed = observed,
                current = gate.current,
                sameNetwork = observedNetworkKey != null && observedNetworkKey == situationNetwork,
                networkChanged = trustOnce,
                holdAgeMillis = silentHoldAge(),
            )
        ) {
            if (silentHoldAt == 0L) silentHoldAt = SystemClock.elapsedRealtime()
            pendingSwitch = false
            settled = false
            Log.i(
                TAG,
                "резолверы молчат ${silentHoldAge() / 1000} с — вижу ${name(observed)}, " +
                    "но это «не знаю», а не «${name(observed)}»: остаюсь на ${name(gate.current)}",
            )
            // Действие повторяем ровно то же, на котором стоим: выбор мог сбиться, а
            // трогать туннель тут нечем и незачем.
            apply(host, gate.current, repeat = true)
            noteRound(observed)
            return gate.current
        }
        silentHoldAt = 0L

        val changed = gate.offer(
            observed,
            trust = trustOnce,
            hurried = burst.active && !trustOnce,
            blind = observationSilent,
        )
        pendingSwitch = gate.pending
        settled = burstClosable(changed = changed, pending = gate.pending, confident = observationConfident)

        when {
            changed -> {
                Log.i(TAG, "обстановка сменилась: ${name(was)} → ${name(observed)}")
                situationNetwork = observedNetworkKey
                publish(auto = true, situation = observed)
                apply(host, observed, repeat = false)
            }

            // Обстановка та же, но выбор мог сбиться (ядро перезапустилось,
            // человек ткнул руками до выключения автомата) — повторяем действие.
            observed == gate.current -> {
                // Заход подтвердил то, на чём стоим, — значит стоим мы на ЭТОЙ сети.
                // Без этой записи «сеть та же» было бы известно только сразу после
                // переключения, то есть ровно тогда, когда броня и не нужна.
                situationNetwork = observedNetworkKey
                apply(host, observed, repeat = true)
            }

            else -> Log.i(TAG, "вижу ${name(observed)}, подтверждения не набраны — пока не трогаю")
        }
        noteRound(observed)
        return gate.current
    }

    private fun observe(host: Host): Situation {
        // Каждый заход начинается зрячим, пока сводка DNS не скажет обратного: иначе
        // молчание одного захода тянулось бы в следующие.
        observationSilent = false
        val network = physicalNetwork() ?: run {
            observedNetworkKey = null
            observationNote = "сети нет вовсе"
            noteLink(null, "заход")
            PathRegistry.allUnavailable("сети нет")
            refreshLink()
            return decide(false, false, false, false)
        }
        observedNetworkKey = networkKey(network)
        // Пока меряем — так и говорим. Иначе экран весь этот десяток секунд утверждает,
        // что всё подключено, хотя ещё ничего не проверено.
        //
        // Держится это ровно на время захода: заход всегда дописывает дому итог ниже,
        // а «проверяю» на экране бьёт «связи нет» — и правильно бьёт, пока проба идёт.
        PathRegistry.probing(PathId.HOME)
        refreshLink()

        // Готовая подсказка про эту сеть, если её уже снимали. Ничего не меряет.
        var hint = cachedHint(network)

        // Дом — это наш собственный роутер, а он раздаёт вайфай или кабель. В соте
        // спрашивать резолвер незачем: ответ известен заранее, а стоил он до 2.5 секунд
        // на каждом заходе (замер 10.08.2026).
        val canBeHome = homeReachable(network)

        // Признак дома (резолвер) и прямой запрос наружу отвечают на разные вопросы и
        // друг друга не ждут. Раньше они шли по очереди, и возвращение домой стоило
        // суммы двух проб вместо большей из них: 2.5 с DNS плюс 5.1 с трафика = 7.6 с
        // до вердикта (замер 10.08.2026). Пробу пускаем вперёд только там, где ответ
        // и так почти наверняка понадобится, — сразу после смены сети и когда стоим
        // дома. На чужом вайфае в обычном ритме лишних запросов не появляется.
        val ahead = if (canBeHome && hint != NetworkMode.Whitelist && speculateHomeTraffic()) {
            aheadHomeTraffic(network)
        } else {
            null
        }

        val dnsNow = if (canBeHome) homeBypass(network) else HomeSign.Sign.No
        // Молчание резолверов доводим до решения отдельным признаком, а не сворачиваем
        // в «не дома» здесь. Ниже оно всё равно схлопнется в булев [dnsHome] — так и
        // должно быть, дом объявляется только доказанным, — но заход, построенный на
        // молчании, обязан оставаться отличимым от захода, который что-то узнал.
        observationSilent = dnsNow == HomeSign.Sign.Unknown
        // Молчание резолверов — самостоятельное событие, а не подробность вердикта:
        // именно оно (4-7 минут при живом интернете) и было причиной «авто режим сам
        // включает VPN на вайфае» 28.08.2026.
        if (canBeHome) noteDnsSilence(network, observationSilent)
        if (dnsNow == HomeSign.Sign.Yes) rememberHomeSign(network)
        // Одна слепая сводка признак не отменяет — отменяет его только опровержение делом.
        val dnsHome = HomeSign.stands(
            seenNow = dnsNow,
            ageMillis = homeSignAge(network),
            refuted = hint == NetworkMode.Whitelist,
        )
        // Трафиком подтверждаем только то, что есть смысл подтверждать. Если подсказка
        // уже сказала «белый список», дом отменён при любых признаках DNS — и тратить
        // на него пробу незачем.
        val carried = when {
            ahead != null -> ahead()
            dnsHome && hint != NetworkMode.Whitelist -> homeCarriesTraffic(network)
            else -> null
        }
        // Наружу не прошло — признак опровергнут делом, и держаться за память о нём
        // больше не на чем.
        if (carried == false) forgetHomeSign()

        // Повод спросить режим сети: что-то не сходится. Дом по DNS без трафика — самый
        // сильный из таких поводов, второй — уже провалившийся основной канал.
        val broken = brokenEnough(
            homeMismatch = dnsHome && carried != true,
            mainFailed = mainFailures > 0,
            settling = burst.active,
        )
        // Дома определитель не спрашиваем вовсе, и это не экономия, а правильность.
        // Замер на телефоне 10.08.2026, возврат на домашний вайфай: сеть ещё не устоялась,
        // TLS не успел подняться, определитель выдал «DPI» за 4187 мс — и этот выдуманный
        // вердикт выкинул автомат из дома в туннель на полторы секунды. Со стороны это
        // и есть «на вайфае зачем-то включается VPN». Дома вопрос «режут ли нас по дороге»
        // смысла не имеет: наружу ходит роутер, а не мы.
        // Уверенность этого захода. Не путать с вердиктом: вердикт может быть верным и
        // при неуверенности — просто на нём нельзя закрывать серию перепроверок.
        observationConfident = when {
            // Дома не бывает в соте: тут узнавать нечего, и ждать нечего.
            !canBeHome -> true
            // Резолверы промолчали — мы ничего не узнали.
            dnsNow == HomeSign.Sign.Unknown -> false
            // Признак есть, а замер трафика не состоялся (имя цели не резолвится на
            // недоделанной сети) — вердикт «не дома» держится на неизмеренном.
            dnsHome && carried == null && hint != NetworkMode.Whitelist -> false
            // Сеть ещё не объявлена системой рабочей или её резолверы не приехали.
            !networkMatured(network) -> false
            else -> true
        }

        val atHome = dnsHome && carried != false
        if (hint != NetworkMode.Whitelist && !atHome &&
            askDetector(broken, hintAge(network), nodeAnswers())
        ) {
            hint = askNetworkMode(network)
        }

        val home = homeVerdict(dnsHome, carried, hint)
        if (canBeHome && (dnsHome || home)) {
            // Признак дома был — значит есть что объяснить: почему домом это считается
            // или почему нет. Без признака писать нечего, там и так обычная сеть.
            Log.i(
                TAG,
                "вердикт «дома»: ${if (home) "да" else "нет"} — признак DNS ${if (dnsHome) "есть" else "нет"}, " +
                    "трафик ${
                        when (carried) {
                            true -> "проходит"
                            false -> "не проходит"
                            null -> "не проверяли"
                        }
                    }, подсказка о сети $hint",
            )
        }
        if (home) {
            PathRegistry.alive(PathId.HOME, lastHomeLatencyMs)
            // Основной канал этим заходом не мерили — так и записываем. Прошлый его
            // отказ был в другой сети и про эту не говорит ничего.
            PathRegistry.unchecked(PathId.MAIN, "дома обход делает роутер")
        } else {
            // «Не отвечает» и «спрашивать было незачем» — разные вещи, и путать их дорого:
            // отказавший путь на экране означает «Связи нет», а в соте дома нет и быть
            // не может. Раньше мобильная сеть каждым заходом получала отказ дома, и все
            // те секунды, что мерился основной канал, человек читал «Связи нет».
            if (canBeHome && !observationSilent) {
                PathRegistry.dead(PathId.HOME, homeReason(dnsHome, carried, hint))
            } else if (canBeHome) {
                // Резолверы промолчали — про дом мы не узнали ничего. Записать сюда отказ
                // значило бы написать человеку «Связи нет» ровно там, где связь живая:
                // именно так выглядел роуминг 28.08.2026 со стороны экрана.
                PathRegistry.unchecked(PathId.HOME, "резолверы молчат — про дом ничего не узнали")
            } else {
                PathRegistry.unchecked(PathId.HOME, "дома можно быть только за своим роутером")
            }
            // Обе записи одним движением: между ними снимок читателю не показываем,
            // иначе экран мигнёт «связи нет» ровно посреди своей же проверки.
            PathRegistry.probing(PathId.MAIN)
        }
        refreshLink()
        val inRoom = gate.current == Situation.Room
        val main = when {
            home -> {
                peekWanted = false
                false
            }
            // Подсказка уже всё сказала: под белым списком адрес узла недостижим на
            // уровне маршрутизации, и честная проба потратила бы полминуты, чтобы
            // узнать ровно это. Пишем в реестр подсказкой ([Evidence.Hint]) — видно,
            // что канал не мерили, а вывели.
            //
            // Кроме одного случая — [measuresMainDespiteHint]: сидя в комнате, мы за
            // подсказкой не видим ничего. Она живёт [HINT_TTL_MILLIS], и всё это время
            // основной путь не меряется вовсе, хотя он мог ожить в первую же минуту.
            hint == NetworkMode.Whitelist && !measuresMainDespiteHint(inRoom, layout.mainPinned) -> {
                PathRegistry.dead(PathId.MAIN, WHITELIST_REASON, Evidence.Hint)
                Log.i(TAG, "основной канал: $WHITELIST_REASON — пробу не тратим")
                // Канал похоронен подсказкой, а не замером. Вот это и опровергает
                // приглядка между заходами — иначе ждать пришлось бы старости подсказки.
                peekWanted = true
                false
            }

            else -> mainWorks(network, host, inRoom = inRoom)
        }
        if (home || main) {
            mainFailures = 0
        } else {
            mainFailures++
        }

        val room = if (home || main) {
            false
        } else {
            // Комната больше не висит круглосуточно, поэтому «стоит ли она» — это ответ
            // на вопрос, который мы сами и создаём. Пробуем поднять, но только когда
            // основной канал провалился уже [ROOM_TRIAL_AFTER] заходов подряд.
            if (mainFailures >= ROOM_TRIAL_AFTER) trialRaiseRoom(host)
            roomAlive()
        }
        noteRoom()
        refreshLink()
        // Снимок связи — раз за заход и только когда он изменился. Роуминг, при котором
        // Android молчит, виден именно здесь.
        noteLink(network, "заход")
        observationNote = "сеть [${observedNetworkKey ?: "?"}]; " +
            "дом: признак DNS ${
                when (dnsNow) {
                    HomeSign.Sign.Yes -> "есть"
                    HomeSign.Sign.No -> "нет"
                    HomeSign.Sign.Unknown -> "не узнали (молчат)"
                }
            }" +
            (if (dnsHome != (dnsNow == HomeSign.Sign.Yes)) " (в силе: $dnsHome)" else "") +
            ", трафик ${
                when (carried) {
                    true -> "проходит"
                    false -> "не проходит"
                    null -> "не проверяли"
                }
            }, подсказка $hint → ${if (home) "дома" else "не дома"}; " +
            "основной ${if (main) "жив" else "нет"} (провалов подряд $mainFailures); " +
            "комната ${if (room) "стоит" else "нет"}" +
            (if (!observationConfident) "; заход неуверенный" else "")
        return decide(hasNetwork = true, home = home, main = main, room = room)
    }

    /**
     * Теневая запись про комнату: что о ней говорит её собственное ядро.
     *
     * Сама таблица перевода живёт в [RoomNote] — её пишет ещё и присмотр, который меряет
     * комнату раз в пять секунд. Раньше писал только автомат отсюда, и между его кругами
     * реестр про комнату молчал по три минуты.
     */
    private fun noteRoom() = RoomNote.note()

    /**
     * Пробный подъём комнаты.
     *
     * Качелей тут нет по трём причинам, и все три нужны:
     *  1. поднимаем не по первому провалу основного канала, а по [ROOM_TRIAL_AFTER]-му подряд —
     *     значит одиночная просадка видеозвонок не будит;
     *  2. гасим не по наблюдению, а по решению задвижки ([apply] зовётся только на смене
     *     обстановки или на её подтверждении) — значит мигание основного канала не роняет
     *     уже поднятую комнату;
     *  3. неудачная попытка удваивает паузу до [ROOM_TRIAL_PAUSE_CAP_MILLIS] — значит
     *     комната, которая не встаёт вообще, не съедает батарею попытками.
     */
    private fun trialRaiseRoom(host: Host) {
        // Уже стоит или как раз встаёт — просить нечего. Подъём теперь идёт своим потоком,
        // и без этой проверки каждый заход добавлял бы к нему вторую просьбу.
        if (roomUp() || roomSettling()) return
        if (layout.room == null || !OlcRtcParams.roomAllowed) return
        val now = SystemClock.elapsedRealtime()
        if (roomTriedAt != 0L && now - roomTriedAt < roomTrialPause) return

        // Туннель погашен — комнату поднимать некуда, и сервис откажет, не начав. Раньше
        // мы всё равно просили, получали мгновенный отказ «туннель погашен» и записывали
        // его комнате в неудачу: пауза удваивалась до двух минут, хотя попытки не было.
        // Поэтому порядок обратный — сперва туннель, потом комната.
        if (!host.tunnelLive()) {
            if (runCatching { host.resumeTunnel("комната нужна, а туннель погашен") }
                    .getOrElse {
                        Log.w(TAG, "туннель поднять не вышло: ${it.message}")
                        false
                    }
            ) {
                selected = null
            }
            if (!host.tunnelLive()) {
                // Туннеля так и нет. Это обстоятельство туннеля, а не комнаты:
                // ни попытки, ни штрафа.
                Log.i(TAG, "туннель не поднялся — комнату в этом заходе не просим, паузу не растим")
                return
            }
        }

        roomTriedAt = now
        PathRegistry.raising(PathId.ROOM)
        Log.i(TAG, "основной канал не поднимается $mainFailures заход(а) подряд — пробую поднять комнату")
        val ack = runCatching { host.setRoomWanted(true, "проверяю, встаёт ли комната") }
            .getOrElse {
                Log.w(TAG, "комнату поднять не вышло: ${it.message}")
                RoomAck.Failed
            }
        if (ack.changed) selected = null
        when {
            // Комнату не спрашивали вовсе — штрафовать не за что и попытки не было.
            ack.untried -> {
                roomTriedAt = 0L
                PathRegistry.coolDown(PathId.ROOM, 0L)
                Log.i(TAG, "комнату не спрашивали ($ack) — пауза не растёт")
            }

            // Подъём идёт. Ответа тут ждать нельзя: он стоит до полутора минут, а автомат
            // всё это время был бы слеп (замер 08.08.2026 — 69 с). Итог принесёт реестр:
            // его пишет присмотр, а пересборку ядра — сам сервис через [onCoreRebuilt].
            ack == RoomAck.Raising || roomUp() || roomSettling() -> {
                roomTrialPause = ROOM_TRIAL_PAUSE_MILLIS
                Log.i(TAG, "комната поднимается, жду вердикта присмотра")
            }

            else -> {
                roomTrialPause = (roomTrialPause * 2).coerceAtMost(ROOM_TRIAL_PAUSE_CAP_MILLIS)
                // Остывание помнит реестр, но распоряжается им по-прежнему [roomTrialPause]:
                // решения из общей памяти на этом шаге не принимает никто.
                PathRegistry.coolDown(PathId.ROOM, System.currentTimeMillis() + roomTrialPause)
                Log.i(TAG, "комната не встала, следующая попытка не раньше чем через ${roomTrialPause / 1000} с")
            }
        }
    }

    /**
     * Собственно решение. Вынесено отдельно и без единого обращения к Android, чтобы
     * таблицу «что видим → куда идём» можно было проверить, а не пересказать.
     */
    internal fun decide(hasNetwork: Boolean, home: Boolean, main: Boolean, room: Boolean): Situation = when {
        !hasNetwork -> Situation.NoNetwork
        home -> Situation.Home
        main -> Situation.Main
        room -> Situation.Room
        else -> Situation.Searching
    }

    /**
     * Обстановка, на которой можно стоять: у неё есть выход и он работает.
     *
     * «Ничего не поднимается» и «неизвестно» сюда не входят намеренно: беречь там
     * нечего, и молчание резолвера не должно запирать нас в состоянии, из которого
     * человек и так не выйдет.
     */
    internal fun working(situation: Situation): Boolean =
        situation == Situation.Home || situation == Situation.Main || situation == Situation.Room

    /**
     * Держим ли вердикт вместо того, чтобы его менять.
     *
     * Единственный ответ на «резолверы молчат» — **«не знаю»**, а «не знаю» ничего не
     * переключает. Приборный повод описан у [SILENCE_HOLD_MILLIS]: DNS немой минутами
     * при живом интернете, и автомат, честно не подтвердив дом, поднимал туннель.
     *
     * Вынесено отдельно и без единого обращения к Android: утверждение «молчание не
     * трогает рабочее состояние, а ответ резолвера трогает всё как раньше» должно
     * проверяться тестом, а не пересказом.
     *
     * @param silent резолверы этого захода промолчали ([observationSilent]).
     * @param observed что заход увидел.
     * @param current обстановка, на которой стоим.
     * @param sameNetwork отпечаток сети тот же, на котором обстановка была подтверждена.
     * @param networkChanged сеть доказанно сменилась — тут держаться не за что вовсе.
     * @param holdAgeMillis сколько уже держим на молчании; 0 — держать только начинаем.
     */
    internal fun holdsVerdict(
        silent: Boolean,
        observed: Situation,
        current: Situation,
        sameNetwork: Boolean,
        networkChanged: Boolean,
        holdAgeMillis: Long,
        capMillis: Long = SILENCE_HOLD_MILLIS,
    ): Boolean = when {
        // Резолвер ответил — всё ровно как раньше, до последней ветки.
        !silent -> false
        // Сеть другая: старый вердикт про неё не говорит ничего, и держать его вредно.
        networkChanged || !sameNetwork -> false
        // И так ничего не меняется — держать нечего.
        observed == current -> false
        // Стоим не на рабочем выходе: беречь нечего, пусть решает как обычно.
        !working(current) -> false
        // Предохранитель: молчание навсегда не должно замораживать автомат навсегда.
        holdAgeMillis >= capMillis -> false
        else -> true
    }

    /** Сколько уже держим вердикт на молчании резолверов; 0 — не держим. */
    private fun silentHoldAge(): Long =
        if (silentHoldAt == 0L) 0L else SystemClock.elapsedRealtime() - silentHoldAt

    private fun apply(host: Host, situation: Situation, repeat: Boolean) {
        // Повтор не пишем: он идёт каждым заходом и говорит ровно то, что уже сказала
        // сводка захода. Пишем настоящий переход — это и есть момент «включил туннель».
        if (!repeat) Log.i(TAG, "действую по обстановке «${name(situation)}»")
        when (situation) {
            Situation.Home -> {
                // Гашение туннеля снимает и ядро комнаты — отдельно просить не надо.
                //
                // Зовём и на повторе тоже. Вызов идемпотентный (погашенный туннель отвечает
                // «ничего не делал»), а поднять туннель теперь может не только [apply]:
                // [trialRaiseRoom] делает это сам, когда комната нужна, а туннеля нет.
                // С прежним `!repeat` поднятый так туннель оставался бы висеть дома до
                // следующей смены обстановки — то есть ровно то, чего дом и избегает.
                if (host.suspendTunnel("дома обход делает роутер")) selected = null
            }

            Situation.Main -> {
                // Ядро поднялось заново — выбор внутри селектора вернулся к тому,
                // что записано в конфиге, и его надо выставить снова.
                if (host.resumeTunnel("основной канал поднимается")) selected = null
                // Ушли на основной канал — видеозвонок больше не нужен. Держать его
                // «на всякий случай» нельзя: круглосуточная сессия и есть то, чего
                // вся схема избегает.
                if (setRoom(host, false, "идём основным каналом").changed) selected = null
                choose(host, layout.main, "обстановка «основной канал»")
            }

            Situation.Room -> {
                if (host.resumeTunnel("основной канал не поднимается")) selected = null
                // Обычно комната уже поднята пробно — вызов идемпотентный и ничего не делает.
                if (setRoom(host, true, "уходим в комнату").changed) selected = null
                choose(host, layout.room, "обстановка «комната»")
            }

            Situation.Searching -> {
                // Ничего не поднимается, но сеть есть: туннель оставляем поднятым —
                // ядро само продолжает пробовать, а мы просто честно это показываем.
                if (host.resumeTunnel("проверяю, что поднимется")) selected = null
                // Комнату при этом НЕ гасим, пока она встаёт. Пробный подъём занимает
                // секунды, а «ничего не поднимается» повторяется каждые 12 — раньше
                // повторный заход гасил комнату ровно в тот момент, когда она поднималась,
                // и автомат навсегда оставался в «ищу путь» (поймано 06.08.2026).
                // Гасим либо по решению задвижки, либо когда присмотр уже вынес приговор.
                //
                // Приговор спрашиваем у самого присмотра, а не у последней пробы. Первая
                // проба только что поднятой комнаты врёт чаще всего: нога заходит в неё до
                // десяти секунд, и одиночный отказ — это почти всегда попадание в её
                // пересборку. Прогон 09.08.2026: комната встала за 7.5 с, первая проба
                // не дождалась ответа, автомат погасил её через 31 секунду и заплатил
                // вторым подъёмом — 66 секунд на ровном месте. У присмотра для того же
                // вопроса три отказа подряд, и он же лечит канал сам, не роняя видеозвонок.
                val judged = OlcRtcWatchdog.condemned
                if (!roomSettling() && (!repeat || judged) &&
                    setRoom(host, false, "комната канала не дала").changed
                ) {
                    selected = null
                }
                // Пока ищем, выход не трогали вовсе, и селектор оставался на том, что стоит
                // в конфиге первым, то есть на основном канале — даже когда комната УЖЕ
                // поднялась и везёт. Задвижке нужно набрать подтверждения, и всё это время
                // трафик уходил в мёртвый узел. Если комната готова, а канала нет,
                // переключаем сразу: хуже точно не будет, а решение задвижки останется
                // за ней.
                if (OlcRtcCore.state is OlcRtcCore.State.Ready && OlcRtcCore.isRunning()) {
                    layout.room?.let { room ->
                        if (selected != room) {
                            Log.i(TAG, "ищу путь, но комната уже стоит — иду ей, не дожидаясь подтверждений")
                            choose(host, room, "канала нет, комната уже стоит")
                        }
                    }
                }
            }

            // Сети нет и обстановка неизвестна: не поднимаем ничего. Комнату при этом
            // гасим — без сети она всё равно мертва, а присмотр за ней будет впустую
            // долбиться в подъём. Поднимется сеть — придёт событие, и заход случится сам.
            Situation.NoNetwork -> if (setRoom(host, false, "сети нет").changed) selected = null

            Situation.Unknown -> Unit
        }
    }

    /** @return чем кончилась просьба. `Changed` — ядро sing-box пересобрано. */
    private fun setRoom(host: Host, wanted: Boolean, reason: String): RoomAck =
        runCatching { host.setRoomWanted(wanted, reason) }
            .getOrElse {
                Log.w(TAG, "комнату переключить не вышло ($reason): ${it.message}")
                RoomAck.Failed
            }
            .also {
                // `Changed` тут бывает только с одной стороны — гашением комнаты
                // (подъём всегда уходит в свой поток и отвечает `Raising`, см.
                // [RoomAck]). Пересборка ядра выдаёт входу пробы новый свободный порт
                // ([ProbeInboundPatch]), а раскладку до сих пор перечитывали только на
                // старте сервиса и на возврате из дома ([onCoreRebuilt]). Круг после
                // выхода из комнаты на основной канал стучался в порт из прошлой жизни
                // ядра, получал молчание и писал «Не отвечает» на живом канале, пока
                // раскладку не обновлял какой-нибудь другой повод (поймано 13.08.2026).
                if (it.changed) refreshLayout(reason)
            }

    /** Какой выход соответствует обстановке. Нужен, когда [selected] стёрт пересборкой ядра. */
    private fun exitFor(situation: Situation): String? = when (situation) {
        Situation.Room -> layout.room
        Situation.Main -> layout.main
        else -> null
    }

    private fun choose(host: Host, tag: String?, why: String = "") {
        val group = layout.chooser ?: return
        val target = tag ?: return
        val was = selected
        if (selected == target) return
        runCatching { host.selectExit(group, target) }
            .onSuccess {
                selected = target
                // Старое значение и причина стоят в той же строке: «переключён на X»
                // не отвечало ни на «откуда», ни на «зачем», а обрыв канала разбирается
                // именно по этой паре.
                Log.i(
                    TAG,
                    "выход переключён: «${was ?: "не выбран"}» → «$target»" +
                        if (why.isBlank()) "" else " ($why)",
                )
            }
            .onFailure { Log.w(TAG, "не удалось переключить выход на «$target»: ${it.message}") }
    }

    private fun delayFor(situation: Situation): Long = when (situation) {
        Situation.Home -> ROUND_HOME_MILLIS
        Situation.Main -> ROUND_MAIN_MILLIS
        Situation.Room -> ROUND_ROOM_MILLIS
        // Сети нет — работы для нас нет, но и спать навсегда нельзя. Раньше здесь стояло
        // «ждём только события от системы» (`Long.MAX_VALUE` = `wait(0)`), а вердикт «сети
        // нет» принимается по ОДНОМУ наблюдению. Ошиблись один раз — и разбудить нас может
        // только смена сети, которой в этой же сети не будет. Страховочный тик стоит одну
        // дешёвую проверку в пять минут и снимает залипание насовсем.
        Situation.NoNetwork -> ROUND_NO_NETWORK_MILLIS
        Situation.Searching, Situation.Unknown -> {
            searchingRounds++
            val grown = ROUND_SEARCHING_MILLIS shl (searchingRounds - 1).coerceIn(0, 5)
            grown.coerceAtMost(ROUND_SEARCHING_CAP_MILLIS)
        }
    }.also { if (situation != Situation.Searching && situation != Situation.Unknown) searchingRounds = 0 }

    private fun waitNext(millis: Long) {
        synchronized(lock) {
            if (!active) return
            try {
                // wait(0) — это «ждать вечно», ровно то, что нужно при отсутствии сети.
                lock.wait(if (millis == Long.MAX_VALUE) 0 else millis)
            } catch (_: InterruptedException) {
                Thread.currentThread().interrupt()
                active = false
            }
        }
    }

