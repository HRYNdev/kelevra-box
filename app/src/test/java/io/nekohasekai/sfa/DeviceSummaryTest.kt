package io.nekohasekai.sfa

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Шапка журнала: чем телефон подписывает свой лог.
 *
 * Повод. В андроидном журнале не было ни модели, ни версии приложения, ни версии
 * системы — вскрытые 02.09.2026 живые файлы на сервере начинались сразу с «=== запись
 * журнала начата, pid ... ===». Кто прислал файл, узнавалось только из реестра
 * устройств, а сам журнал об этом молчал; у десктопного клиента такая шапка есть с
 * самого начала, и разбор аварии там начинается с неё.
 *
 * Проверяем то, от чего шапка зависит:
 *  1. в строке есть все три факта и ровно в том виде, в каком они уходят серверу;
 *  2. пустое поле называется словами, а не исчезает молча;
 *  3. шапка однострочная — иначе первая строка журнала перестаёт быть первой.
 */
class DeviceSummaryTest {

    @Test
    fun `шапка несёт версию, модель и систему`() {
        assertEquals(
            "Kelevra 1.14.104, samsung SM-A525F, android 12",
            Kelevra.describeDevice("samsung SM-A525F", "12", "1.14.104"),
        )
    }

    @Test
    fun `без версии системы остаётся хотя бы платформа`() {
        assertEquals(
            "Kelevra 1.14.104, HUAWEI VOG-L29, android",
            Kelevra.describeDevice("HUAWEI VOG-L29", "", "1.14.104"),
        )
    }

    /**
     * Прошивка может не отдать модель, а сборка — версию. Молча съеденное поле не
     * отличить от того, что его забыли записать вовсе, поэтому дырка называется словами.
     */
    @Test
    fun `пустые поля названы словами, а не пропущены`() {
        val строка = Kelevra.describeDevice("", "", "")
        assertEquals("Kelevra версия неизвестна, модель неизвестна, android", строка)
    }

    /** Шапка обязана быть одной строкой: иначе она перестаёт быть первой строкой журнала. */
    @Test
    fun `шапка не разваливается на несколько строк`() {
        val строка = Kelevra.describeDevice("Xiaomi 23021RAAEG", "13", "1.14.104")
        assertTrue(строка.isNotBlank())
        assertEquals(1, строка.lines().size)
    }
}
